// [解析] 【谁创建】Core/Src/freertos.c：osThreadDef(LED, led_task, osPriorityLow, 0, 128);
// [解析]           优先级最低（osPriorityLow），因为它只是"装饰"，
// [解析]           不应该跟遥控器、电机这些控制类任务抢 CPU。
// [解析] 【硬件】TIM5 的三个通道 CH1/CH2/CH3 -> 引脚 PH10/PH11/PH12，对应 R/G/B。
// [解析] 【原理】LED 亮度靠 PWM 占空比控制：占空比 0 = 全暗，1 = 全亮。
// [解析]         set(r, g, b) 三个颜色分量取值范围都是 [0, 1]。
// [解析] 【小提示】若实际点出来的颜色和预期不符，多半是 CH1/2/3 与 R/G/B 的对应顺序反了，
