// [解析] ==========================================================================

#include "cmsis_os.h"
#include "io/led/led.hpp"

// [解析] 用 TIM5 输出 PWM 驱动 LED。只传定时器句柄，
// [解析] 具体用哪几个通道在 led.cpp 内部固定好了。
sp::LED led(&htim5);

extern "C" void led_task(void const * argument)
{
  // [解析] 启动 PWM 输出。调用之后才会真的开始驱动 LED。
  led.start();

  while (true) {
    // [解析] ↓↓↓ 下面这 4 段是被作者注释掉的"红色 / 绿色"渐变代码。
    // [解析]   它们和后面蓝色那两段写法完全一样，只是换了颜色通道：
    // [解析]     led.set(b*0.01f, 0, 0)  -> 只点亮红色通道
    // [解析]     led.set(0, g*0.01f, 0)  -> 只点亮绿色通道
    // [解析]   作者现在只用蓝色，其余保留在这里当"备选素材"，
    // [解析]   想看别的颜色就把对应几行的注释去掉、把蓝色那段注释掉。
    // for (uint8_t b = 0; b < 10; b++) {
    //   led.set(b * 0.01f, 0, 0);
    //   osDelay(100);
    // }

    // for (uint8_t b = 10; b > 0; b--) {
    //   led.set(b * 0.01f, 0, 0);
    //   osDelay(100);
    // }
    // for (uint8_t g = 0; g < 10; g++) {
    //   led.set(0, g * 0.01f, 0);
    //   osDelay(100);
    // }

    // for (uint8_t g = 10; g > 0; g--) {
    //   led.set(0, g * 0.01f, 0);
    //   osDelay(100);
    // }

    // [解析] 蓝色"渐亮"：b 从 0 数到 9，蓝色占空比从 0.00 涨到 0.09，每步停 100ms。
    // [解析]   整段约 1 秒，肉眼看就是慢慢亮起来。
    // [解析]   （只涨到 0.09 而不是 1.0，是因为循环条件写的是 b < 10，
    // [解析]     想让灯更亮可以把 10 改大，比如 100。）
    for (uint8_t b = 0; b < 10; b++) {
      led.set(0, 0, b * 0.01f);
      osDelay(100);
    }

    // [解析] 蓝色"渐暗"：b 从 10 数到 1，占空比从 0.10 退回 0.01。
    // [解析]   渐亮 + 渐暗两段拼起来，就是一个循环的呼吸灯。
    for (uint8_t b = 10; b > 0; b--) {
      led.set(0, 0, b * 0.01f);
      osDelay(100);
    }
    // [解析] 到这里回到 while(true) 开头，继续渐亮，如此往复、永不停止。
  }
}
