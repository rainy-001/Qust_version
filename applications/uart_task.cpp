// [解析] ==========================================================================
// [解析] 【文件】applications/uart_task.cpp
// [解析] 【作用】遥控器接收任务：读取 DBus 遥控器（就是比赛用的那个遥控器）的
// [解析]         摇杆、拨杆、鼠标、键盘数据，供其他任务使用。
// [解析] 【谁创建】Core/Src/freertos.c：
// [解析]           osThreadDef(DBUS, uart_task, osPriorityRealtime, 0, 256);
// [解析]           注意优先级是 osPriorityRealtime（最高），因为遥控器数据晚了就危险。
// [解析] 【硬件】USART3（huart3），C 板上 DBus 接收机接在这里，波特率 100000。
// [解析] 【工作机制】"请求-回调"式：
// [解析]   request() 启动一次接收 -> 收满一帧后 HAL 触发 HAL_UARTEx_RxEventCallback
// [解析]   回调里 update() 解析数据，然后再 request() 一次，如此循环接力。
// [解析] ==========================================================================

#include "cmsis_os.h"
#include "io/dbus/dbus.hpp"

// C板
// [解析] remote：遥控器对象。第 2 个参数是"是否使用 DMA"，
// [解析]   这里没写，用的是头文件里的默认值 true —— C 板走 DMA 接收。
sp::DBus remote(&huart3);

// 达妙
// [解析] 达妙板的遥控器接收机接在 USART5，而且不用 DMA，所以要显式传 false。
// [解析] 换板子时把上面那行注释掉、下面这行放开即可。
// sp::DBus remote(&huart5, false);

extern "C" void uart_task()
{
  // [解析] 发起第一次接收请求。之后每收完一帧都会自动重新请求（见下面的回调），
  // [解析] 所以整个程序生命周期里只需要在这里调用一次。
  remote.request();

  // [解析] 数据解析是在中断回调里完成的，本任务其实无事可做，
  // [解析] 只需要"挂着"让任务不返回即可。
  while (true) {
    // 使用调试(f5)查看remote内部变量的变化
    // [解析] 调试小技巧：在 IDE 里按 F5 进入调试，把 remote 加到 watch 窗口，
    // [解析]   就能实时看到摇杆这些变量随你推动遥控器而变化，用来确认接收正常。
    osDelay(10);
  }
}

// [解析] ==========================================================================
// [解析] 串口"收到一帧/空闲"事件回调。HAL 库在 DMA 或 IDLE 方式收完数据后调用它。
// [解析] 参数 Size = 本次实际收到的字节数。
// [解析] ★ 这是中断里的代码，必须尽量短。
// [解析] ==========================================================================
extern "C" void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef * huart, uint16_t Size)
{
  // [解析] 记录这一帧的接收时刻（毫秒），用于判断遥控器是否掉线（is_alive）。
  auto stamp_ms = osKernelSysTick();

  // [解析] USART3 和 USART5 可能共用这个回调，所以先确认是遥控器那一路。
  if (huart == &huart3) {
    // [解析] 解析刚收到的数据：Size 是长度，stamp_ms 是时间戳。
    // [解析] 解析完 remote.ch_lh / ch_lv / sw_l ... 这些成员就更新好了。
    remote.update(Size, stamp_ms);
    // [解析] 立刻再发起一次接收请求，接力等下一帧。
    // [解析] 如果不写这一行，接收只会发生一次，遥控器数据就永远停在第一帧了。
    remote.request();
  }
}

// [解析] ==========================================================================
// [解析] 串口出错回调：比如帧错误、噪声、溢出等。
// [解析] 出错后 HAL 会停止当前接收，必须重新 request() 才能恢复，
// [解析] 否则遥控器会"永久失联"。这是串口中断接收一个经典必写点。
// [解析] ==========================================================================
extern "C" void HAL_UART_ErrorCallback(UART_HandleTypeDef * huart)
{
  if (huart == &huart3) {
    remote.request();
  }
}
