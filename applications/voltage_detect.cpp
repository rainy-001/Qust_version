// [解析] ==========================================================================
// [解析] 【文件】applications/voltage_detect.cpp
// [解析] 【作用】电池电压检测任务：用 ADC 采集分压后的电池电压，得到整车电量信息。
// [解析] 【谁创建】Core/Src/freertos.c：osThreadDef(ADC, adc_task, osPriorityAboveNormal, 0, 128);
// [解析] 【原理】STM32 的 ADC 引脚最多只能承受 3.3V，而电池是 24V 左右，
// [解析]         所以硬件上先用两个电阻"分压"，把高电压按比例降下来再测量，
// [解析]         软件里再乘回这个"分压比"还原真实电压。
// [解析] 【本文件最重要的一件事】第 5 行是 C 板配置、第 8 行是深大飞镖板配置。
// [解析] ==========================================================================

#include "cmsis_os.h"
#include "io/adc/adc.hpp"

// C 板：PF10 / ADC3_IN8；
// [解析] 五个参数依次是：
// [解析]   &hadc3              —— 用 ADC3 这个外设
// [解析]   12                  —— ADC 是 12 位精度（读数范围 0~4095）
// [解析]   3.3f                —— 参考电压 3.3V
// [解析]   (222.0f / 22.0f)    —— 分压比 ≈ 10.09。
// [解析]                          含义：222kΩ 和 22kΩ 两个电阻分压，
// [解析]                          即真实电压 = 测得电压 × 222/22。写成算式而不是
// [解析]                          直接写 10.09，是为了让硬件改电阻时一眼能对上。
// [解析]   1.0f                —— 测量偏差补偿，C 板为 1.0V
sp::Adc battery(&hadc3, 12, 3.3f, (222.0f / 22.0f), 1.0f);
// 深大飞镖控制板专用配置如下
// F411：PC4 / ADC1_IN14；直接测量引脚电压，分压比 1，补偿 0V。
// [解析] 深大飞镖板的 ADC 是 12 位、3.3V 参考，但硬件上不分压（分压比 1.0）、
// [解析] 也不需要补偿（0.0V），所以参数不一样。换板子时切换这两行即可。
// sp::Adc battery(&hadc1, 12, 3.3f, 1.0f, 0.0f);

// [解析] 全局变量：保存最近一次测得的电池电压。
// [解析] 定义成全局是为了让别的任务/文件也能读到它（比如发给视觉或做低电压保护）。
float voltage = 0.0f;

extern "C" void adc_task(void * argument)
{
  // [解析] 任务函数的参数用不到，但编译器会对"未使用的参数"报警告，
  // [解析] 写成 (void)argument; 就是告诉编译器"我故意不用它"，属于消除警告的惯用写法。
  (void)argument;
  // [解析] 初始化 ADC（启动校准等），只需一次。
  battery.init();
  while (true) {
    // [解析] update() 会"启动一次转换 -> 等它完成 -> 读结果"，
    // [解析]   成功返回 true，失败返回 false。
    // [解析]   只有成功时才更新 voltage，这样偶发失败不会把电压冲成 0，
    // [解析]   变量里始终保留着上一次的可信值。
    if (battery.update()) {
      voltage = battery.voltage;  // 只使用本次成功转换的结果
    }
    // [解析] 每 10ms 采一次（100Hz）。电压变化很慢，不需要采太快。
    osDelay(10);
  }
}
