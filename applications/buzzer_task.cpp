// [解析] 【作用】蜂鸣器任务：用 PWM 驱动蜂鸣器，上电后"嘀"三声提示程序已启动。
// [解析] 【谁创建】Core/Src/freertos.c：osThreadDef(BUZZER, buzzer_task, osPriorityAboveNormal, 0, 128);
// [解析] 【原理】蜂鸣器发声靠"方波频率"：改变 PWM 频率就能改变音调，
// [解析]         改变 PWM 占空比就能改变音量（0.5 时最响）。
// [解析] 【本文件最重要的一件事】第 5 行配置的是"C 板"，第 8 行是"达妙板"，
// [解析]   换板子时要改的就是这一行（以及那个时钟频率参数）。
// [解析] ==========================================================================

#include "cmsis_os.h"
#include "io/buzzer/buzzer.hpp"

// C板
// [解析] 三个参数分别是：
// [解析]   &htim4        —— 用 TIM4 这个定时器产生 PWM
// [解析]   TIM_CHANNEL_3 —— 用 TIM4 的第 3 个通道
// [解析]   84e6          —— 定时器的时钟频率 84MHz（=84×10^6）。
// [解析]                   这个值很重要：Buzzer 内部用它反算出"要发声频率该设多大的分频/重载值"，
// [解析]                   填错了音调就会不对。
sp::Buzzer buzzer(&htim4, TIM_CHANNEL_3, 84e6);

// 达妙
// [解析] 达妙（DM）开发板的蜂鸣器接在 TIM12 通道 2，且定时器时钟是 240MHz。
// [解析] 换成达妙板时，把上面 C 板那行注释掉，把下面这行的注释去掉即可。
// sp::Buzzer buzzer(&htim12, TIM_CHANNEL_2, 240e6);

extern "C" void buzzer_task()
{
  // [解析] set(频率, 占空比)：设成 5000Hz、占空比 0.1。
  // [解析]   注意 set() 只是"准备好参数"，还要靠 start() 才真的响。
  buzzer.set(5000, 0.1);

  // [解析] 循环 3 次：响 100ms -> 停 100ms，也就是连续"嘀、嘀、嘀"三声。
  for (int i = 0; i < 3; i++) {
    buzzer.start();
    osDelay(100);
    buzzer.stop();
    osDelay(100);
  }

  // [解析] 提示音放完后本任务就没有事情做了，但不能让函数返回！
  // [解析] FreeRTOS 的任务函数一旦 return 会触发错误（任务被删除/断言失败），
  // [解析] 所以必须用"死循环 + 延时"让任务永远挂在这里，把 CPU 让给别人。
  while (true) {
    osDelay(100);
  }
}
