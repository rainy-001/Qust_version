void SetNoteFrequency(uint16_t frequency){
	if (frequency == 0) {
		__HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_3, 0);
		return;
	}
	uint32_t timerFreq = 1000000;
	uint32_t arrValue = (timerFreq / frequency) - 1;
	float dutyCycle = (volume > 100) ? 50 : (volume * 50 / 100);
	uint32_t ccrValue = (uint32_t)(arrValue * dutyCycle / 100.0f);
	HAL_TIM_PWM_Stop(&htim4, TIM_CHANNEL_3);

	__HAL_TIM_SET_AUTORELOAD(&htim4, arrValue);
	__HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_3, ccrValue);
	HAL_TIM_PWM_Start(&htim4, TIM_CHANNEL_3);
}

void PlayMusic(const uint8_t* music){
	if (music[musicIndex] != 0xFF) {
		Note_t note = music[musicIndex];
		musicIndex++;
		uint8_t duration = music[musicIndex];
		musicIndex++;

		SetNoteFrequency(noteFrequencies[note]);
		HAL_Delay(SPEED / 8 * duration);
		SetNoteFrequency(0); 
		HAL_Delay(5);
	} else {
		musicIndex = 0xFFFF;
		HAL_GPIO_WritePin(GPIOH,GPIO_PIN_12,1);
		HAL_GPIO_WritePin(GPIOH,GPIO_PIN_11,0);
		SetNoteFrequency(0);
		HAL_Delay(1);
	}
}
