// [解析]         运动学解算器：calc() 把整车速度变成左右轮目标转速，
// [解析]         update() 把左右轮实测转速还原成整车速度。
// [解析] 【被谁用】本仓库里暂时没有调用者，属于中间件工具库。
// [解析]         上层 applications/ 的底盘任务自己建对象，例如：
// [解析]           sp::DiffDrive diff(0.2f, 0.06f, false, false);  // 半轮距 0.2m、半径 0.06m
// [解析]           diff.calc(v, w);
// [解析] 【关键点】1) 构造参数顺序容易被记反：先"半轮距 half_width"，后"轮子半径"；
// [解析]           2) v 是前进速度(m/s)，w 是旋转角速度(rad/s)，两者是"整车"的量；
// [解析]           3) 轮距是"两个驱动轮中心距的一半"，量错了原地自转会转快或转慢。
// [解析] 【阅读顺序】先看本文件了解接口，再看 diff_drive.cpp 看两行公式。
// [解析] ==========================================================================

#ifndef SP__DIFF_DRIVE_HPP
#define SP__DIFF_DRIVE_HPP

namespace sp
{
// [解析] DiffDrive 类：一个对象代表一辆两轮差速底盘。
// [解析] 差速底盘的原理：只有左右两个驱动轮，靠"左右轮转速差"实现转弯，
// [解析]   左右等速 -> 直行；左右反向等速 -> 原地自转（旋转中心在两轮中点）。
// [解析] 本类不做任何硬件操作、不保存历史状态，纯粹是"算数工具"，
// [解析]   所以可以在中断和任务里放心调用（但要注意别和别的任务同时写同一对象）。
class DiffDrive
{
public:
  // [解析] 构造函数：登记轮距、半径和两个电机的装配方向。
  // [解析] half_width：左右驱动轮中心距的一半，单位 m。★注意它是"一半"，不是整个轮距。
  // [解析] wheel_radius：轮子半径，单位 m（不是直径）。
  // [解析] reverse_l / reverse_r：左/右电机是否反装。true 表示该电机正转对应车后退。
  // [解析] 没有默认值：必须显式传 4 个参数，避免新手漏传装配方向导致车"原地打转"。
  DiffDrive(float half_width, float wheel_radius, bool reverse_l, bool reverse_r);

  // [解析] ---- update() 的输出（轮速 -> 整车速度）----
  // [解析] v：底盘前进速度，单位 m/s，+ 表示朝车头方向前进。
  // [解析] w：底盘旋转角速度，单位 rad/s，+ 表示俯视逆时针（右手螺旋，大拇指朝上）。
  float v = 0;  // 只读! update()更新结果, 前进速度, 单位: m/s
  float w = 0;  // 只读! update()更新结果, 旋转速度, 单位: m/s
  // [解析] 注意：上面 w 的行末注释写的是"单位: m/s"，但角速度的正确单位是 rad/s
  // [解析]   （作者应该是复制上一行忘了改）。这里按原样保留，不要照它的单位去理解。

  // [解析] ---- calc() 的输出（整车速度 -> 轮速）----
  // [解析] speed_l / speed_r：左右轮的目标转速，单位 rad/s，直接作为电机 PID 的目标值。
  float speed_l = 0;  // 只读! calc()计算结果, left目标转速, 单位: rad/s
  float speed_r = 0;  // 只读! calc()计算结果, right目标转速, 单位: rad/s

  // [解析] calc()：正运动学。输入"整车期望速度"，输出"左右轮各转多快"。
  // [解析] v_set：期望前进速度，单位 m/s（需要停住就传 0，需要后退就传负数）。
  // [解析] w_set：期望旋转角速度，单位 rad/s（不是角度！）。
  // [解析] 调用时机：每个控制周期调一次，紧接着把 speed_l/speed_r 交给两个电机 PID。
  // [解析] 副作用：写 speed_l / speed_r。
  void calc(float v_set, float w_set);
  // [解析] update()：反运动学，也是里程计。输入左右轮实测转速，算出整车速度。
  // [解析] motor_speed_l / motor_speed_r：左右电机反馈转速，单位 rad/s。
  // [解析] 调用时机：拿到电机反馈后调用；对 v 积分得位移，对 w 积分得车头朝向。
  // [解析] 副作用：写 v / w。
  void update(float motor_speed_l, float motor_speed_r);

private:
  // [解析] w_：半轮距，单位 m。它决定"转弯时左右轮速度差多少"，也决定反解时分母的大小。
  // [解析] r_：轮子半径，单位 m。用来在 m/s 和 rad/s 之间换算。
  // [解析] sign_l_ / sign_r_：装配方向符号，只取 +1.0f 或 -1.0f。
  const float w_;
  const float r_;
  const float sign_l_;
  const float sign_r_;
};

}  // namespace sp

#endif  // SP__DIFF_DRIVE_HPP