#include "omni.hpp"

// [解析] <cmath> 是为了下面的 std::sqrt（在构造函数初始化列表里算 d_ 用）。
// [解析] 用 std::sqrt 而不是 sqrt，是为了明确调用的是 C++ 标准库版本，避免和 C 库宏冲突。
#include <cmath>

namespace sp
{
// [解析] 构造函数：把几何尺寸和装配方向登记好，不做硬件操作。
// [解析] 【d_ 的来历】d_ = sqrt(half_length² + half_width²)，也就是"轮心到底盘中心的距离"，
// [解析]   即矩形底盘半对角线长度。四个轮子装在四个角上，它们到中心的距离都一样，
// [解析]   所以只需要算一个值给四个轮子共用。
// [解析] 【为什么不用 l_ 或 w_ 代替 d_】因为轮子的滚动方向 u 是沿对角线的垂线，
// [解析]   把"整车平移速度"投影到 u 上时，分母就是这条对角线的长度 D，
// [解析]   而自转带来的额外线速度是"角速度 × 旋转半径"，半径同样等于 D。
// [解析]   所以 d_ 在正解里要除以一次（投影）、乘以一次（自转半径）。
// [解析] 【sqrt 的开销】这个计算只在构造对象时做一次（一般在 main 初始化阶段），
// [解析]   运行时的 calc()/update() 只是乘除加减，对 STM32F407 没有浮点压力问题。
// [解析] 【初始化列表顺序提示】成员按类中声明顺序初始化：r_, l_, w_, d_, sign_*。
// [解析]   这里 d_ 用到了 half_length / half_width 这两个"构造参数"（形参），
// [解析]   而不是 l_ / w_ 成员，所以即使顺序变化也不会读到未初始化的成员，是安全的写法。
Omni::Omni(
  float wheel_radius, float half_length, float half_width, bool reverse_lf, bool reverse_lr,
  bool reverse_rf, bool reverse_rr)
: r_(wheel_radius),
  l_(half_length),
  w_(half_width),
  d_(std::sqrt(half_length * half_length + half_width * half_width)),
  sign_lf_((reverse_lf) ? -1.0f : 1.0f),
  sign_lr_((reverse_lr) ? -1.0f : 1.0f),
  sign_rf_((reverse_rf) ? -1.0f : 1.0f),
  sign_rr_((reverse_rr) ? -1.0f : 1.0f)
{
  // [解析] 四个输出先清零，防止"还没调过 calc() 就读 speed_xx"读到内存里的随机值。
  this->speed_lf = 0.0f;
  this->speed_lr = 0.0f;
  this->speed_rf = 0.0f;
  this->speed_rr = 0.0f;
}

// [解析] calc()：正运动学。输入"我期望整车怎么动"，输出"四个轮子各转多快"。
// [解析] 【三个输入】vx：前进速度（+ 向车头），单位 m/s；
// [解析]            vy：左移速度（+ 向车身左侧），单位 m/s；
// [解析]            wz：绕竖直轴角速度（+ 为俯视逆时针），单位 rad/s。
// [解析] 【副作用】写 this->speed_lf / lr / rf / rr，单位 rad/s。
// [解析] 【陷阱】形参 vx / vy / wz 与成员变量同名；函数体里裸写 vx 用的是形参。
// [解析] 【调用时机】每个控制周期开始时调一次，紧接着把四个 speed_xx 送给电机 PID。
// [解析] 【为什么这么算】轮子只能沿自己的滚动方向 u 产生驱动，所以
// [解析]   轮子线速度 = u · (整车主速度 v + 自转带来的附加速度 wz × p)。
// [解析]   把四个轮子的 p（位置）和 u（滚动方向）代进去，就得到下面四行。
void Omni::calc(float vx, float vy, float wz)
{
  // 各轮滚动方向上的线速度: u · (v + wz × p) = (-y * vx + x * vy) / D + D * wz, 单位: m/s
  // 注意 x = l_ 处为车头方向, y = w_ 处为车身左侧
  // [解析] 上面这条公式拆成两半看待，就非常好懂了：
  // [解析]   前半段 (-y*vx + x*vy)/D  —— 纯平移分量，把整车速度投影到轮子的滚动方向 u 上；
  // [解析]      其中 (x, y) 是该轮的位置 p，D 是半对角线长 d_（用来做归一化）。
  // [解析]   后半段 D*wz             —— 纯自转分量，线速度 = 角速度 × 旋转半径，半径就是 d_。
  // [解析] 注意 D*wz 这一项对四个轮子都是"同号的正值"，这一点和麦轮完全不同
  // [解析]   （麦轮的 wz 是"左侧负、右侧正"）。原因是四个全向轮的滚动方向 u
  // [解析]   都沿绕中心的切线方向，底盘逆时针自转时四个轮子确实朝同一侧滚，
  // [解析]   所以纯 wz > 0 时四轮同向正转 —— 和 omni.hpp 里原作者写的结论一致。
  // [解析] 各轮的位置 p = (x, y)（x 表示前后，+x 在车头侧；y 表示左右，+y 在车身左侧）：
  // [解析]   LF: p=(+l, +w)  LR: p=(-l, +w)  RF: p=(+l, -w)  RR: p=(-l, -w)
  // [解析] 把 p 代进 (-y*vx + x*vy)/d_ 就能看出每个系数是怎么来的：
  // [解析]   vx 的系数是 -y/d_：LF/LR 在左侧（y=+w）→ 系数 -w_；RF/RR 在右侧（y=-w）→ +w_。
  // [解析]     所以 vx 项是"左侧取负、右侧取正"，即左右两侧反号；
  // [解析]   vy 的系数是 +x/d_：LF/RF 在车头侧（x=+l）→ +l_；LR/RR 在车尾侧（x=-l）→ -l_。
  // [解析]     所以 vy 项是"前排取正、后排取负"，即前后两排反号。
  // [解析] 这正是原作者在 omni.hpp 里总结的规律：纯 vx 时 LF/LR 反转、RF/RR 正转；
  // [解析]   纯 vy 时 LF/RF 正转、LR/RR 反转。可以拿上面的系数直接对上。
  const float v_lf = (-w_ * vx + l_ * vy) / d_ + d_ * wz;
  const float v_lr = (-w_ * vx - l_ * vy) / d_ + d_ * wz;
  const float v_rf = (+w_ * vx + l_ * vy) / d_ + d_ * wz;
  const float v_rr = (+w_ * vx - l_ * vy) / d_ + d_ * wz;
  // [解析] 上面四行算出来的是"轮子滚动方向上的线速度 v_xx"，单位 m/s。
  // [解析] 注意 v_rf 写成 +w_ * vx 只是表明了符号，编译结果和 w_ * vx 完全一样。

  // 线速度 / 半径 = 转速, 再按电机装配方向取反
  // [解析] v_xx / r_：线速度(m/s) ÷ 半径(m) = 角速度(rad/s)，这就是电机侧的目标转速。
  // [解析] × sign_xx_：最后统一翻转装配方向，正数表示"按标准方向转"，
  // [解析]   负数表示反转。reverse 参数的作用只在这里体现，和上面的几何推导完全解耦。
  // [解析] 注意：这里没有限幅。如果 vx 给得很大，算出来的轮速会超过电机能力上限，
  // [解析]   限幅要在调用方（给 PID 设目标之前）自己做。
  this->speed_lf = sign_lf_ * v_lf / r_;
  this->speed_lr = sign_lr_ * v_lr / r_;
  this->speed_rf = sign_rf_ * v_rf / r_;
  this->speed_rr = sign_rr_ * v_rr / r_;
}

// [解析] update()：反运动学（里程计）。输入四个轮子的实测转速，反推整车速度。
// [解析] 【四个输入】speed_lf/lr/rf/rr：轮子实测转速，单位 rad/s，符号代表转向。
// [解析]   一般来自电机反馈（注意：如果电机回传的是"转子侧"转速，要自己先除以减速比）。
// [解析] 【副作用】写 this->vx / this->vy / this->wz（m/s、m/s、rad/s）。
// [解析] 【自检方法】把 calc() 的输出直接喂给 update()，理论上应还原出原来的 (vx,vy,wz)；
// [解析]   实车调试时用这条验证符号有没有接错，非常有效。
// [解析] 【陷阱】形参名和成员变量 speed_xx 同名，函数体里裸写的是形参。
void Omni::update(float speed_lf, float speed_lr, float speed_rf, float speed_rr)
{
  // 电机转速 -> 各轮滚动方向上的线速度, 单位: m/s
  // [解析] ÷sign_xx_：先抵消装配方向（符号只有 ±1，除和乘等价），把量统一到"标准约定"下。
  // [解析] ×r_：单位换算 rad/s -> m/s。
  // [解析] 注意这个表达式的运算顺序是 (speed / sign) * r_，和 speed / (sign * r_) 等价，
  // [解析]   因为乘除同级、从左到右结合。
  const float v_lf = speed_lf / sign_lf_ * r_;
  const float v_lr = speed_lr / sign_lr_ * r_;
  const float v_rf = speed_rf / sign_rf_ * r_;
  const float v_rr = speed_rr / sign_rr_ * r_;

  // 最小二乘反解 (H^T H 为对角阵, 故为精确解)
  // [解析] 为什么"最小二乘"在这里反而给出精确解？
  // [解析]   正解可以写成矩阵形式 u = H · (vx, vy, wz)，H 是 4×3（4 个轮子、3 个自由度），
  // [解析]   不是方阵，普通逆矩阵不存在。但 H 的三列两两正交（互相点乘恰好为 0），
  // [解析]   于是 H^T·H 变成对角阵，最小二乘解 (H^T H)^(-1) H^T u 里的求逆
  // [解析]   就退化成"分别除以每列的模长平方"，也就是下面看到的 /4 和 /d_。
  // [解析]   所以结果是精确的，不是近似 —— 全向底盘能同时做到"任意方向平移 + 自转"
  // [解析]   并且里程计无损，根子就在这个正交性上。
  // [解析] 三行公式的系数规律（v_xx 就是上面算出来的轮子线速度）：
  // [解析]   vx = (-v_lf - v_lr + v_rf + v_rr) / 4 × d_ / w_   ← 左右反号
  // [解析]   vy = (+v_lf - v_lr + v_rf - v_rr) / 4 × d_ / l_   ← 前后反号
  // [解析]   wz = (+v_lf + v_lr + v_rf + v_rr) / 4 / d_        ← 四轮同号，再除以旋转半径 d_
  // [解析] 注意 vx 后面乘的 d_/w_、vy 后面乘的 d_/l_ 是"列模长倒数"化简后的结果：
  // [解析]   vx 列的模长平方是 4w²/d_²，其倒数就是 d_²/(4w²)，乘上分子里的 4w 就剩下 d_/w_。
  // [解析]   因为 d_ ≥ w_，这个系数总是 ≥ 1，会把轮速噪声放大，所以实测值一般要先滤波。
  // [解析] 自检：设原地纯自转、四个轮子线速度大小都是 u，按符号规律
  // [解析]   v_lf = v_lr = -u、v_rf = v_rr = +u，代入 wz 行得 4u/4/d_ = u/d_，
  // [解析]   而物理上 u = d_·ω，正好还原出 ω ✓
  // [解析] 本函数不做滤波、不做打滑补偿：轮速实测抖动会 1:1 传到结果里。
  this->vx = (-v_lf - v_lr + v_rf + v_rr) / 4 * d_ / w_;
  this->vy = (+v_lf - v_lr + v_rf - v_rr) / 4 * d_ / l_;
  this->wz = (+v_lf + v_lr + v_rf + v_rr) / 4 / d_;
}

}  // namespace sp
