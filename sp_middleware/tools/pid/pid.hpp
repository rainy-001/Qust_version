// [解析] ==========================================================================
// [解析] 【文件】sp_middleware/tools/pid/pid.hpp
// [解析] 【作用】通用 PID 控制器的声明。一个 PID 对象 = 一个"闭环控制器"，
// [解析]         每个控制周期喂进"目标值 set"和"反馈值 fdb"，它就吐出"输出值 out"。
// [解析] 【被谁用】tools/gimbal、tools/swerve、tools/omni、tools/mecanum、tools/joint
// [解析]         这些上层控制器里都各挂着好几个 PID 成员（例如云台的 yaw/pitch 各一个）。
// [解析] 【背景知识】PID = 比例(P) + 积分(I) + 微分(D)：
// [解析]   P 项：误差越大、输出越大，是主力；调大响应快但容易振荡。
// [解析]   I 项：把"历史误差"一点点累加，专门消除"稳态误差"（总是差一点点到不了目标）；
// [解析]         调大消除快，但太大会超调/积分饱和。
// [解析]   D 项：看误差的"变化速度"，起阻尼刹车作用，抑制超调；但它会放大噪声。
// [解析] 【关键点】1) 本文件有 4 个同名重载 calc()，参数个数不同，容易调错那一个；
// [解析]   2) 构造函数参数顺序是 dt, kp, ki, kd, max_out, max_iout，别把后两个限幅写反；
// [解析]   3) angular 与 dynamic 两个 bool 开关会明显改变算法行为，见下面逐条说明。
// [解析] 【阅读顺序】先看本文件了解"参数含义和开关"，再看 pid.cpp 看公式怎么算。
// [解析] ==========================================================================

#ifndef SP__PID_HPP
#define SP__PID_HPP

#include "tools/math_tools/math_tools.hpp"

namespace sp
{
// [解析] PIDData 是这个控制器的"体检报告 + 内部草稿纸"：既保存了中间状态（供下次计算用），
// [解析] 也把 P/I/D 各项的分解输出暴露出来，方便你在调试时（比如用 oled/上位机看曲线）
// [解析] 判断"到底是哪一项在捣乱"。外面的代码只应该读它，不要写它（写了会破坏内部状态）。
struct PIDData
{
  float set = 0;  // 设定值
  // [解析] ↑ 上一次 calc() 传进来的目标值（setpoint）。单位由调用者决定，例如 rad。
  float fdb = 0;  // 反馈值(feedback)
  // [解析] ↑ 上一次 calc() 传进来的反馈值。注意：微分先行算法用的正是"上一帧的 fdb"。

  float pout = 0;  // P项输出值
  // [解析] ↑ P 项单独的输出 = kp * err[0]，已经按 max_out 限过幅。
  float iout = 0;  // I项输出值
  // [解析] ↑ I 项的累加器（有记忆！）。它从 0 开始，每个周期加上一小块积分增量，
  // [解析]   并被 max_iout 夹在 [-max_iout, +max_iout] 内。clear() 会把它清零。
  float dout = 0;  // D项输出值
  // [解析] ↑ D 项单独的输出。

  float err[3] = {0};   // 误差缓冲区
  // [解析] ↑ 三个元素的"滑动窗口"：err[0] 是本周期误差(最新)，err[1] 是上一周期，
  // [解析]   err[2] 是上上周期。为什么需要三个？因为算积分用的是 err[1]。
  // [解析]   每周期开头把 err[1] 挪到 err[2]、err[0] 挪到 err[1]，俗称"数据移位/打拍"。
  float dbuf[3] = {0};  // D项滤波器缓冲区
  // [解析] ↑ 同样是个滑动窗口，但它装的不是误差，而是"反馈值的变化量"（微分先行）。
  // [解析]   dbuf[0] 最新，dbuf[1]/dbuf[2] 是更早的样本。

  float trapezoid = 0;   // 梯形积分
  // [解析] ↑ 本周期的"积分增量"（还没乘 ki）。梯形法用 (本周期误差+上周期误差)/2 * dt 来
  // [解析]   近似"误差曲线下的面积"，比矩形法（只取本周期误差*dt）更准。
  float dynamic_ki = 0;  // 动态积分
  // [解析] ↑ 变速积分用的"临时 ki"：ki / (1 + |err|)。
  // [解析]   误差小时分母接近 1，ki 几乎不变；误差大时分母变大，ki 自动变小，
  // [解析]   这样刚上电/目标突变时不会疯狂积分导致超调。只有 dynamic=true 才真正生效。
};

// [解析] PID 类：一个对象负责一路量的闭环控制（一个电机、一个关节、一个云台轴……）。
// [解析] 典型用法（注意：构造参数一次性给全，之后只调 calc）：
// [解析]   sp::PID pid(1e-3f, 10.0f, 0.5f, 0.05f, 20.0f, 10.0f);  // 1kHz 控制周期
// [解析]   每周期：pid.calc(target, now);
// [解析]            motor.set_current(pid.out);
// [解析] 【重要】PID 只做数学计算，不碰任何硬件、不做任何延时、不在内部自己定时；
// [解析]   你必须让它和电机控制代码同一个周期被调用，dt 必须和真实调用周期一致。
class PID
{
public:
  // dt: 控制周期, 单位: s
  // kp: P项系数
  // ki: I项系数
  // kd: D项系数
  // max_out: PID最大输出值
  // max_iout I项最大输出值
  // alpha: D项滤波系数, alpha=1时不滤波
  // [解析] 【参数逐个说清楚】
  // [解析]   dt      ：调用周期，单位秒。1kHz 就写 1e-3f。写错会直接导致 I/D 两项算错。
  // [解析]   kp/ki/kd：三个增益，没有固定公式，靠试凑/看波形调。初学建议先 kp，再加 kd，最后加 ki。
  // [解析]   max_out ：总输出的对称限幅，最终 out 一定落在 [-max_out, +max_out]。
  // [解析]              典型含义：这是给电机的电流/力矩指令最大值，单位由你决定（A 或 N·m）。
  // [解析]   max_iout：只限制 I 项，防止"积分饱和"（积分累到很大，反向时半天爬不回来）。
  // [解析]              取值一般比 max_out 小，比如 max_out 的一半左右。
  // [解析]   alpha   ：D 项低通滤波系数，范围 [0, 1]。1 = 不滤波（最灵敏，也最容易被噪声干扰）；
  // [解析]              越小滤波越强。取值必须落在 0~1，传 1.5 或 -0.1 都会算出乱七八糟的结果。
  // [解析]   angular ：true 表示"这一路控制的是角度"。
  // [解析]              角度有个特殊问题：359° 和 1° 只差 2°，但直接相减得到 358°。
  // [解析]              打开后会先做 limit_angle() 折叠，让误差始终落在 (-π, π]，取最短转向。
  // [解析]              控制位置/速度/电流时保持 false。
  // [解析]   dynamic ：true 表示启用"变速积分"（上面 dynamic_ki 那段）。
  // [解析]   注意：构造函数不会清零 out / data，但成员都有默认值 0，所以刚建好就是干净状态。
  PID(
    float dt, float kp, float ki, float kd, float max_out, float max_iout, float alpha = 1,
    bool angular = false, bool dynamic = false);

  float out = 0;  // 只读! PID输出值
  // [解析] ↑ calc() 算完的结果，已经按 max_out 限过幅。请不要从外部直接改它。
  PIDData data;   // 只读! PID计算数据
  // [解析] ↑ 上面那个结构体，调试时可以用它看 P/I/D 各项分别是多少。

  // 计算PID输出值
  // set: 目标值
  // fdb: 反馈值(feedback)
  // [解析] 【重载 1】最常用的版本，只喂目标值和反馈值。
  // [解析] D 项走"微分先行"：用 (上一帧 fdb - 本帧 fdb) 当微分来源，
  // [解析] 好处是"目标值突变时 D 项不会瞬间爆冲"（不会产生微分尖峰）。
  // [解析] 副作用：会更新 data 里的所有中间状态、推进 err/dbuf 窗口、累加 data.iout。
  // [解析] 调用时机：每个控制周期调用一次，且必须严格按周期调用。
  void calc(float set, float fdb);

  // [解析] 【重载 2】在重载 1 的基础上多一个"积分分离阈值"。
  // [解析] integral_pause_threshold：当 |P 项输出| 超过这个阈值时，本周期的积分增量记 0，
  // [解析]   也就是"误差还很大就先别积分"，等接近目标了再开始积分，避免起步时积分堆太高。
  // [解析]   单位与 PID 输出一致（因为它比较的是 pout）。传一个很大的值就相当于不启用。
  void calc(float set, float fdb, float integral_pause_threshold);

  // [解析] 【重载 3】"前馈"版本：额外直接给出目标速度和反馈速度。
  // [解析] set_dot：目标值的变化率（如目标角速度，rad/s）；fdb_dot：反馈值的变化率。
  // [解析] D 项变成 kd * (set_dot - fdb_dot)，不再用内部差分，
  // [解析]   适合"速度已经由传感器直接测出来"的场合（比如电机自带转速反馈），比数值微分干净。
  // [解析] 注意：这个版本不会使用 alpha 滤波，也不会动 dbuf，而且 I 项没有变速积分效果。
  void calc(float set, float fdb, float set_dot, float fdb_dot);
  // [解析] 【重载 4】= 重载 3 + 积分分离阈值，参数含义同上，是"全功能"版本。
  void calc(float set, float fdb, float set_dot, float fdb_dot, float integral_pause_threshold);

  // 清零PID的所有状态（输出与缓存等）
  // [解析] 把 out、P/I/D 输出、err/dbuf 窗口、积分累加器全部归零，并清掉"已有一帧微分"的标志。
  // [解析] 什么时候用：使能电机前、模式切换时、长时间没调用后重新接管时。
  // [解析] 【踩坑提醒】不清零直接接管，上一轮残留的 iout 会让电机"一上电就冲一下"。
  void clear();

private:
  // [解析] 下面这些成员全部是 const，意思是"构造时定好，之后永不改变"。
  // [解析] 这样既防止误改，也能让编译器更好地优化。所以想改增益只能重新构造一个对象。
  const float dt_;  // [解析] 控制周期(s)。I/D 两项都直接依赖它。
  const float kp_, ki_, kd_;  // [解析] 三个增益。注意 ki_ 在 dynamic 模式下还要除以 (1+|err|)。
  const float max_out_, max_iout_;  // [解析] 输出限幅、积分限幅，都用于 limit_max() 对称限幅。
  const float alpha_;  // [解析] D 项滤波系数 [0,1]。
  const bool angular_;  // 是否为角度控制
  // [解析] ↑ true 时所有误差都先过 limit_angle() 折到 (-π, π]。
  const bool dynamic_;  // 是否为变速积分
  // [解析] ↑ true 时用 data.dynamic_ki 代替 ki_ 去乘积分增量。
  bool dout_ready_ = false;
  // [解析] ↑ "微分是否已经准备好"的标志。第一帧调用时没有上一帧 fdb 可减，
  // [解析]   所以第一帧只把它置 true 并跳过分母计算，从第二帧起才算真正的微分。
  // [解析] clear() 会把它复位成 false，于是下一次 calc() 又会"重新起步"。
};

}  // namespace sp

#endif  // SP__PID_HPP