// [解析] 【作用】线性跟踪微分器（LTD / 二阶线性观测器）：输入一个带噪声的信号 v，
// [解析]         它同时输出两样东西 —— x1 是"平滑后的信号"，x2 是"信号的微分（变化率）"。
// [解析] 【解决什么问题】直接用 (本帧-上帧)/dt 求微分，噪声会被放大成剧烈抖动
// [解析]         （俗称"微分噪声爆炸"）。本类内部是一个二阶低通系统，
// [解析]         求导和平滑一步到位，比"先低通再差分"效果更好、相位滞后更小。
// [解析] 【被谁用】需要"从位置信号里干净地拿到速度"的场合，例如某些速度环/前馈补偿；
// [解析]         可以和 tools/low_pass_filter 对比使用。典型写法：
// [解析]           sp::LinearDifferentiator diff(30.0f, 1e-3f);
// [解析]           diff.update(encoder_position);
// [解析]           float smooth_pos = diff.x1, speed = diff.x2;
// [解析] 【关键点】1) r 是唯一的调参旋钮，越大跟得越快、噪声也越大；
// [解析]   2) 继承自经典的"二阶线性跟踪微分器"差分方程，参数固定为临界阻尼（无超调）设计；
// [解析]   3) 第一次 update() 会自动初始化，但初始化的那一刻微分强制为 0（详见 .cpp）。
// [解析] 【阅读顺序】先看本文件了解两个输出和两个参数，再看 .cpp 的两行差分方程。
