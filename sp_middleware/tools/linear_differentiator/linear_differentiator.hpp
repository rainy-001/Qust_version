#ifndef SP__LINEAR_DIFFERENTIATOR_HPP
#define SP__LINEAR_DIFFERENTIATOR_HPP

namespace sp
{
// [解析] 线性跟踪微分器。和 LowPassFilter 一样"有记忆"（内部保留 x1/x2 状态），
// [解析] 所以每一路需要微分的信号都要单独一个对象。
// [解析] 【单位说明】x1 的单位 = 输入 v 的单位；x2 的单位 = 输入单位 / 秒。
// [解析]   例如输入是角度(rad)，则 x1 是 rad，x2 是 rad/s。
class LinearDifferentiator
{
public:
  /*
   * @param r 调节带宽参数，值越大跟踪越快，但对噪声的放大也越大
   * @param dt 积分步长，通常为系统的离散时间间隔（如 0.001s）
   */
  // [解析] 【参数 r 怎么理解】它是一个"带宽/收敛速度"参数，单位是 1/秒（rad/s 量级）。
  // [解析]   可以把它当成滤波器截止频率的直观刻度：
  // [解析]     r 小（如 5）  → 输出很平滑，但输入真变化时会跟不上（滞后大）；
  // [解析]     r 大（如 100）→ 跟得非常快，但输入里的噪声也会原样出现在 x2 上。
  // [解析]   【经验选法】先看信号的真实最高变化频率 f，取 r ≈ (3~5) × 2πf 试起，
  // [解析]     然后一边看波形一边加大到"刚好够快、噪声还能接受"为止。
  // [解析]   【内部原理】差分方程里 r 以 r² 和 2r 的形式出现，这对应二阶系统
  // [解析]     特征方程 s² + 2r·s + r² = 0，是一个"双重极点"（临界阻尼）设计，
  // [解析]     所以 x1 跟踪阶跃输入时不会超调、不会振荡 —— 这正是"线性"跟踪微分器的特征。
  // [解析] 【参数 dt】调用周期，单位秒。必须和真实调用间隔一致（1kHz 就填 1e-3f），
  // [解析]   填错会让跟踪速度和微分值整体缩放失真。dt 不能为 0。
  // [解析] 【注意】两者都必须大于 0，代码里没有做检查，传 0 或负数会得到发散/无意义的结果。
  LinearDifferentiator(float r, float dt);

  float x1;  // 跟踪的平滑值
  // [解析] ↑ 滤波后的信号（对输入的"平滑跟随"），单位与输入 v 相同。
  // [解析]   它就是你要拿去当"干净信号"用的那个值。
  float x2;  // 微分值（速度）
  // [解析] ↑ 信号的微分，单位是"输入单位/秒"。它就是"用平滑方式求出来的导数"。
  // [解析]   【注意】首次 update() / init() 之后 x2 被强制置 0，
  // [解析]     因为它无法凭空知道"进入稳态之前信号在往哪个方向变"。

  /*
   * @param v 观测目标输入值
   */
  // [解析] 喂入一个新的采样值并推进一次观测器。
  // [解析] 参数 v：目标输入值（原始测量值，可以带噪声），单位随意但要保持恒定不变。
  // [解析] 副作用：更新 x1 / x2 两个公开成员。
  // [解析] 调用时机：每个控制周期调用一次，且周期要均匀（对应构造时的 dt）。
  // [解析] 【注意】如果从没调用过 init()，第一次 update() 会自动帮你初始化
  // [解析]   （x1 直接取 v、x2 置 0 并立即返回），所以首拍不会有微分输出。
  void update(float v);

  /*
   * @brief 重置内部状态
   */
  // [解析] 手动重置：把平滑值直接设成给定的 v，微分清零，并标记为"已初始化"。
  // [解析] 参数 v：希望观测器从哪个值开始跟踪（一般填当前实际测量值）。
  // [解析] 什么时候用：使能控制前、传感器重新上电/重新标定后、
  // [解析]   或者信号长时间中断后重新接入时 —— 避免拿陈旧状态去算微分。
  void init(float v);

private:
  // [解析] 带宽参数 r（= 跟踪速度），构造时定死，之后不可改。
  float r_;
  // [解析] 调用周期 dt，单位秒。差分方程里用它做积分步长。
  float dt_;
  // [解析] 是否已完成初始化。false 时 update() 会自动调用 init()，不执行差分方程。
  bool inited_;
};
}  // namespace sp

#endif  // SP__LINEAR_DIFFERENTIATOR_HPP
