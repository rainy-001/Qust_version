// [解析] 【文件】sp_middleware/tools/linear_differentiator/linear_differentiator.cpp
// [解析] 【作用】线性跟踪微分器的实现，核心只有两行差分方程（见 update()）。
// [解析] 【数学背景】本类实现的是下面这个二阶线性系统（连续域）：
// [解析]     dx1/dt = x2                        （x1 是信号的平滑跟随）
// [解析]     dx2/dt = -r²·(x1 - v) - 2r·x2      （x2 是微分，v 是输入）
// [解析]   把第二式整理成 (x1-v) 的误差方程：误差'' + 2r·误差' + r²·误差 = 0，
// [解析]   特征方程 (s+r)² = 0 有双重根 -r —— 这就是"临界阻尼"：
// [解析]   跟踪既快又不过冲，是整个控制理论里最经典的一种观测器极点配置。
// [解析] 【离散化】代码用最简单的"前向欧拉法"：x_next = x + dt × dx/dt。
// [解析]   所以 dt 必须和真实调用周期一致；dt 越大，欧拉法的近似误差越大。
// [解析] 【和"直接差分求导"的区别】直接差分是 y[n] = (v[n]-v[n-1])/dt，
// [解析]   噪声会被原样放大。这里的 x2 是被上面那个二阶低通系统"塑形"过的，
// [解析]   等价于给微分加了一级二阶低通，噪声抑制好得多，代价是有一点相位滞后。
// [解析] ==========================================================================

#include "linear_differentiator.hpp"

namespace sp
{

// [解析] 构造函数：初始化列表把两个参数存进成员，并把状态清零。
// [解析] 【注意】x1 和 x2 在这里被显式初始化为 0.0f。
// [解析]   它们和 inited_ 是"配套"的：inited_=false 表示这两个 0 只是占位符，
// [解析]   不是真实的观测状态；第一次 update() 或 init() 会把它们覆盖掉。
// [解析]   所以在调用 update()/init() 之前，请不要去读 x1 / x2，那没有物理意义。
// [解析] 函数体为空：构造阶段不做任何计算、不碰硬件。
LinearDifferentiator::LinearDifferentiator(float r, float dt)
: x1(0.0f), x2(0.0f), r_(r), dt_(dt), inited_(false)
{
}

// [解析] 重置内部状态，让观测器"从现在开始"跟踪。
// [解析] 参数 v：新的起始跟踪值，通常填当前的实际测量值。
// [解析] 【为什么 x2 要置 0】微分代表"信号正以多快的速度变化"，
// [解析]   重置的这一刻我们并没有关于变化趋势的任何信息，
// [解析]   强行给一个非零的 x2 只会让第一拍产生虚假的速度输出。
// [解析]   置 0 表示"重新起步时先当作静止"，让 x2 靠自己从后续采样里慢慢估计出来。
// [解析] 【典型用法】电机使能前调一次 init(当前编码器读数)，
// [解析]   这样从第一拍开始 x1 就是准的，不会有一段时间的"追赶过程"。
void LinearDifferentiator::init(float v)
{
  x1 = v;
  // [解析] 平滑值直接跳到输入值，跳过"从 0 慢慢爬"的过程。
  x2 = 0.0f;
  // [解析] 微分清零，避免虚假速度尖峰。
  inited_ = true;
  // [解析] 标记已初始化。之后 update() 就会走正常的差分方程分支了。
}

// [解析] 推进一次观测器：每个控制周期调用一次。
// [解析] 参数 v：本次的输入采样值。
// [解析] 返回值：无，结果在公开成员 x1（平滑值）和 x2（微分）里。
void LinearDifferentiator::update(float v)
{
  if (!inited_) {
    // [解析] 【首次调用自动初始化】还没人调用过 init()，就先用本次输入值起步，
    // [解析]   然后直接返回 —— 所以第一次 update() 不会产生任何微分输出（x2=0）。
    // [解析]   这样做的好处：调用者不必记得手动 init()，不会因为 x1 从 0 开始而
    // [解析]   在起步阶段算出一个巨大的假误差（比如真实位置是 3.14，却从 0 开始追）。
    // [解析]   代价：如果你想立刻拿到速度，会白等一拍。
    init(v);
    return;
  }

  // 离散化线性跟踪微分器差分方程
  // [解析] 【第 1 行】x1_next = x1 + dt × x2
  // [解析]   对应连续方程 dx1/dt = x2，也就是"位置按当前速度前进"。
  // [解析]   用当前 x2（旧值）而不是更新后的 x2，这就是最朴素的"前向欧拉法"。
  // [解析] 【注意】这两个 xxx_next 是局部变量，先把两个新值都算完，
  // [解析]   再统一赋值回 x1/x2（见下面两行）。这叫"同步更新"，
  // [解析]   如果先写 x1 = x1_next 再算 x2_next，x2_next 里就会混入新时刻的 x1，
  // [解析]   差分方程的含义就变了（相当于半隐式欧拉，行为会不一致）。
  float x1_next = x1 + dt_ * x2;
  // [解析] 【第 2 行】x2_next = x2 + dt × (-r²(x1 - v) - 2r·x2)
  // [解析]   逐项拆开看：
  // [解析]     -r_*r_*(x1 - v)：校正项。x1 落后于输入 v 时 (x1-v) 为负，
  // [解析]        整体变成正数，于是把 x2 往上推，x1 就加速追上去。
  // [解析]        系数是 r 的平方，所以 r 稍微调大一点，收敛速度就明显变快。
  // [解析]     -2.0f*r_*x2：阻尼项。x2 越大，这一项把 x2 拉回得越狠。
  // [解析]        系数恰好是 2r（不是别的值），这正是让系统工作在"临界阻尼"、
  // [解析]        既不欠阻尼振荡也不过阻尼迟钝的关键 —— 换句话说，2r 是解出来的，
  // [解析]        不是拍脑袋凑的。改它会破坏跟踪微分器的良好特性。
  // [解析]   【r 与噪声的关系】-r²(x1-v) 这一项同时也在放大 v 里的噪声，
  // [解析]     r 越大放大越猛，这就是"跟踪快"与"噪声大"这对矛盾的来源。
  float x2_next = x2 + dt_ * (-r_ * r_ * (x1 - v) - 2.0f * r_ * x2);

  // [解析] 统一写回状态（同步更新），本次 update() 结束。
  // [解析]   下一拍进来时用的就是这两个新值。
  x1 = x1_next;
  x2 = x2_next;
}

}  // namespace sp