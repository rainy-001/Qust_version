// [解析] 【文件】sp_middleware/tools/low_pass_filter/low_pass_filter.cpp
// [解析] 【作用】一阶低通滤波的实现，总共只有 20 行，核心其实就一行加权平均公式。
// [解析] 【核心公式】out = alpha × 本次输入 + (1 - alpha) × 上次输出
// [解析]   直观理解：把新旧两个值按比例"调和"一下。alpha 越大越信任新值。
// [解析] 【为什么能滤掉高频噪声】噪声的特点是在真值附近快速上下跳，
// [解析]   加权平均相当于"多看几拍再决定"，跳变被平摊掉了；但真值本身的变化
// [解析]   也会被平摊，所以输出必然滞后 —— 平滑与滞后永远是矛盾的，只能取舍。
// [解析] 【工程上等价的说法】这是一阶 IIR 滤波器，alpha 与截止频率的关系为
// [解析]   fc ≈ alpha / (2π × dt)（dt 是调用周期）。所以 alpha 要配合控制频率一起调。
// [解析] ==========================================================================

#include "low_pass_filter.hpp"

namespace sp
{
// [解析] 构造函数：初始化列表里把 alpha 存进成员，同时把 inited_ 置为 false，
// [解析]   表示"还没有收到过第一帧数据"。
// [解析] 【注意】这里没有给 last_ 初始化，也没有初始化 out。
// [解析]   这是安全的，因为第一次 update() 会走初始化分支，直接用输入值覆盖 last_，
// [解析]   并不会去读那个未初始化的 last_。但 out 在首次 update() 前是不可读的。
LowPassFilter::LowPassFilter(float alpha) : alpha_(alpha), inited_(false) {}

// [解析] 滤波主函数：每来一个新采样调用一次。
// [解析] 参数 value：本次采样值（单位随意，滤波器不关心量纲）。
// [解析] 返回值：无。结果请读公开成员 out。
void LowPassFilter::update(float value)
{
  if (!inited_) {
    // [解析] 【首次调用特例】这是本文件最容易看漏但很重要的一段。
    // [解析] 如果第一帧就按公式算：out = alpha×value + (1-alpha)×0，
    // [解析]   那么输出会从 0 起步、慢慢往上爬（"冷启动爬升"）。
    // [解析]   例如真实值恒为 100、alpha=0.1，要爬十几拍才接近 100。
    // [解析]   控制回路里这种缓慢爬升会被当成"系统反应迟钝"，甚至引发误判。
    inited_ = true;
    // [解析] 标记"已初始化"，以后不再走这个分支。
    last_ = value;
    // [解析] 直接把第一帧当作历史值，相当于"相信第一次读数"。
    this->out = value;
    // [解析] 输出也直接等于第一帧，做到"上电瞬间就给出正确量级"。
    return;
    // [解析] 直接返回，所以第一帧不会执行下面的加权平均公式。
  }

  // [解析] 核心公式：新值占 alpha_，历史值占 (1-alpha_)。
  // [解析]   注意用的是 last_（上一次的滤波结果），不是上一次的原始输入 ——
  // [解析]   也就是"输出反馈到输入"的 IIR 结构，这正是它能累积平滑效果的原因。
  this->out = alpha_ * value + (1 - alpha_) * last_;
  // [解析] 把本次结果存成历史值，供下一次调用使用。这一行是滤波器的"记忆"。
  // [解析]   注意存的是 out 而不是 value：如果存原始输入，滤波器会退化成两点平均（FIR），
  // [解析]   平滑能力弱得多。
  last_ = this->out;
}

}  // namespace sp
