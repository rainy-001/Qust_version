// [解析] 【文件】sp_middleware/tools/low_pass_filter/low_pass_filter.hpp
// [解析] 【作用】一阶低通滤波器（也叫"一阶惯性滤波"、"指数加权移动平均"）。
// [解析]         它能把信号里的高频毛刺/噪声抹平，代价是输出会有一点滞后。
// [解析] 【被谁用】项目里凡是"传感器读数太抖"的地方都可以用，例如
// [解析]         tools/linear_differentiator 的输入、各 motor 的速度反馈，
// [解析]         以及各种需要平滑的遥控/传感器通道。典型写法：
// [解析]           sp::LowPassFilter filter(0.2f);
// [解析]           filter.update(raw);
// [解析]           float smooth = filter.out;
// [解析] 【关键点】1) alpha 是"新值的权重"，越小越平滑但越滞后；
// [解析]   2) 第一次 update() 会直接采用输入值，避免从 0 慢慢爬上去（详见 .cpp）。
// [解析] 【阅读顺序】只有 20 行实现，直接看 low_pass_filter.cpp 最快。
// [解析] ==========================================================================

#ifndef SP__LOW_PASS_FILTER_HPP
#define SP__LOW_PASS_FILTER_HPP

namespace sp
{
// [解析] 低通滤波器类。注意它"有记忆"：内部保存了上一次的输出 last_，
// [解析] 所以每个需要滤波的物理量都必须有自己的对象，不能多个信号共用一个实例。
// [解析] 【线程/中断安全】没有加锁、也没有 volatile。如果 update() 会在中断里被调用，
// [解析]   而主循环又在读 out，请自己保证不会同时读写（例如只在同一个任务里调用）。
class LowPassFilter
{
public:
  // alpha: 为1时, 无滤波效果; 为0时, 无更新效果
  // [解析] 【参数速记】alpha 是"新来数据的权重"，取值范围 [0, 1]：
  // [解析]   1.0  ：完全相信新数据，输出 = 输入，等于没滤波（噪声原样穿过）。
  // [解析]   0.5  ：新旧各占一半，平滑一点点。
  // [解析]   0.1  ：90% 沿用历史，输出非常平滑，但明显滞后。
  // [解析]   0.0  ：只看历史，输出永远卡在第一次的值上，等于"不再更新"。
  // [解析] 【怎么选】一般从 0.2 左右试起。控制周期越快（dt 越小），同样的 alpha 滤波越弱，
  // [解析]   所以换控制频率时通常要重新调 alpha。
  // [解析] 【注意】代码里没有对 alpha 做范围检查。传 1.5 会让输出发散（越算越大），
  // [解析]   传负数会造成振荡，务必自己保证在 [0, 1] 内。
  LowPassFilter(float alpha);

  float out;  // 只读! update()的计算结果
  // [解析] ↑ 最近一次 update() 的滤波结果。构造后、第一次 update() 之前它是未初始化的
  // [解析]   （注意：本类没有给 out 写默认值），所以别在 update() 之前去读它。
  // [解析]   读它和读 update() 的返回值是等价的（虽然 update() 并不返回值）。

  // [解析] 喂入一个原始采样值，滤波器内部更新一次，结果写进 out。
  // [解析] 参数 value：本次采样值，单位随意（滤波本身不关心量纲，只做加权平均）。
  // [解析] 副作用：更新内部状态 last_ 和公开成员 out。
  // [解析] 调用时机：每次拿到新采样就调一次，采样节奏要均匀；
  // [解析]   如果采样间隔忽长忽短，实际滤波强度也会跟着变。
  // [解析] 【重要特性】第一次调用是特例：直接把输入抄给 out，不做加权平均（见 .cpp）。
  void update(float value);

private:
  // [解析] 滤波系数，const 表示构造后不可改。想换系数只能重建一个对象。
  const float alpha_;
  // [解析] 是否已经完成"首次初始化"，避免第一帧从 0 开始慢慢爬起来。
  bool inited_;
  // [解析] 上一次的输出值（滤波器的"记忆"）。下一次 update() 就是拿它和新数据做加权。
  float last_;
};

}  // namespace sp

#endif  // SP__LOW_PASS_FILTER_HPP
