// [解析] 接收缓冲区大小，50 字节。
// [解析] 裁判系统帧头 5 + 命令码 2 + 数据段(SRefereeCustomData 约 33 字节) + 帧尾 2 ≈ 42 字节，
// [解析] 留到 50 是给"粘包"（两帧连在一起）留一点余量。注意这只是一帧的余量，
// [解析] 如果一帧超过 50 字节就会被硬截断，解析自然失败。
constexpr size_t VT02_BUFF_SIZE = 50;

// [解析] 自定义控制器（VT02 图传遥控器）发给机器人的控制数据，来自命令码 0x0302。
// [解析] packed 的含义：告诉编译器"不要为了访问效率在成员之间插空隙"，
// [解析]   强制结构体每个成员的偏移量就是它前面所有成员大小之和。
// [解析]   为什么必须要它？因为这份数据是从串口"照抄"进内存的，
// [解析]   一旦编译器按 4 字节对齐填充，成员偏移就和协议里的字节位置错开了，读出来全是垃圾。
// [解析] 风险提示：packed 结构体里取 float 成员时，若地址不是 4 的倍数，
// [解析]   在部分内核（如 Cortex-M0）上会触发硬件异常；F407（M4）允许非对齐访问，所以这里安全。
// [解析] 这份数据整体大小 = 1+8*4+1 = 34 字节（8 个 float + 1 个保留字节）。
// [解析] 注意：0x0302 官方结构体只有 30 字节，这里多了 control/j0..j5/gripper 共 8 个 float，
// [解析]   属于本项目自定义的"扩展"约定，必须和发数据那一端（图传上位机）严格对齐。
struct __attribute__((packed)) RefereeCustomData
{
  // [解析] 下面 8 个 float 必须和上位机（图传发送端）的约定逐一对齐，顺序错一个就全错。
  // [解析] 每个成员都是 IEEE-754 单精度浮点、小端序，STM32F407 正好也是小端，所以可以直接 memcpy。
  // [解析] 单位不是协议规定的，而是"双方自己约定"的（比如 j0 可能是角度、也可能是弧度），
  // [解析]   调试时务必先确认上位机发的是什么单位，否则会出现"数值对但动作差 57 倍"的诡异现象。
  float control;
  float j0;
  float j1;
  float j2;
  // [解析] 后 4 个成员：j3/j4/j5 是另外三个关节，gripper 是夹爪/末端执行器。
  float j3;
  float j4;
  float j5;
  float gripper;
  uint8_t reserved;  //保留位
  // [解析] ↑ 原注释"保留位"意思是：这一字节现在没用，只是为了凑齐/占位。
  // [解析]   如果哪天协议要新增一个 8 位字段，就直接用这一位，避免改结构体长度。
};

// [解析] 鼠标数据（来自 0x0304 帧）。注意：本文件里没有 packed，因为它不是直接
// [解析] 从串口内存拷贝过来的，而是解析完逐个字段填进去的，对齐不影响正确性。
// [解析] ⚠ 现状：vt02.cpp 的 update() 只处理 0x0302，所以这个结构体不会被赋值。
struct RefereeMouseData
{
  float vx;  // 取值范围: [-1, 1]
  // [解析] ↑ 归一化后的横向速度指令。1 表示"往右最快"，-1 表示"往左最快"。
  // [解析]   这么设计是为了让上层控制代码与具体硬件解耦：不管鼠标 DPI 多少都是 -1~1。
  float vy;  // 取值范围: [-1, 1]
  // [解析] ↑ 纵向速度指令，正方向由上层约定（通常是向上为正）。
  float vs;  // 取值范围: [-1, 1], 鼠标滚轮, s代表scroll
  // [解析] ↑ 滚轮，用来控制某些"连续量"（例如云台俯仰微调）。
  // [解析] left/right 分别是鼠标左键和右键是否按下，用来控制开火/自瞄之类的动作。
  bool left;
  bool right;
};

// [解析] 键盘数据（来自 0x0304 帧）。一共 16 个按键，每个按键用一个 bool 表示按下/松开。
// [解析] 为什么偏偏是这 16 个键？因为裁判系统协议里键盘就是一个 16 位 bitmask，
// [解析]   这 16 个键正好对应 bit0~bit15（参见 vt03.hpp 里的 VT03_KEY_xxx_MASK）。
// [解析] ⚠ 现状：同样因为 update() 只处理 0x0302，这个结构体也不会被赋值。
// [解析] 顺带一提：C++ 里 bool 占 1 字节，所以 16 个 bool 是 16 字节，而不是 2 字节。
struct RefereeKeysData
{
  bool w;
  bool s;
  bool a;
  bool d;
  bool shift;
  bool ctrl;
  bool q;
  bool e;
  bool r;
  bool f;
  bool g;
  bool z;
  bool x;
  bool c;
  bool v;
  bool b;
};

// [解析] VT02 类：一个对象管理一路串口上的 VT02 图传接收机。
// [解析] 典型用法（4 步，和 io/can/can.hpp 的 CAN 类套路一致）：
// [解析]   1) sp::VT02 vt02(&huart3);   // 构造函数只记句柄，不碰硬件
// [解析]   2) vt02.request();          // 启动一次"空闲中断 DMA 接收"
// [解析]   3) 串口中断回调里 vt02.update(HAL_GetTick());  // 解析
// [解析]   4) 主循环里读 vt02.custom / vt02.is_alive() 做控制
class VT02
{
public:
  // [解析] 构造函数。参数：huart 是串口句柄（传 &huart3 这种），不可为 nullptr；
  // [解析] use_dma=true 用 DMA 接收（省 CPU，推荐），false 则退化成中断接收。
  VT02(UART_HandleTypeDef * huart, bool use_dma = true);

  // [解析] 下面 3 个成员是"公共只读缓冲区"：解析结果不通过返回值给出，
  // [解析] 而是由 update() 直接写进这些成员，上层随时读取即可。
  RefereeCustomData custom;  // 只读!
  // [解析] ↑ 遥控器（自定义控制器）发来的控制量，0x0302 解析结果。
  RefereeMouseData mouse;    // 只读!
  // [解析] ↑ 鼠标状态。⚠ 当前实现不会更新它，读到的永远是默认值（0/false）。
  RefereeKeysData keys;      // 只读!
  // [解析] ↑ 键盘状态。⚠ 同上，当前实现不会更新它。

  // [解析] 启动接收：让串口以"空闲中断 + DMA/中断"的方式往内部缓冲 buff_ 里收数据。
  // [解析] 必须在中断回调 update() 之前调用；每处理完一帧后要重新调用一次，
  // [解析]   否则接收只发生一次就停了（这是 HAL 的 ReceiveToIdle 系列的特性）。
  void request();
  // [解析] 解析函数：一般放在串口接收中断/空闲回调里，把 buff_ 里的字节拆成上面的成员。
  // [解析] 参数 stamp_ms 是"当前时刻"（通常填 HAL_GetTick()，单位 ms），
  // [解析]   用来记录 last_read_ms_，是 is_alive() 判断超时的依据。
  // [解析] 副作用：校验通过且命令码为 0x0302 时，会覆盖 custom 并更新"活着"的时间戳。
  void update(uint32_t stamp_ms);
  // [解析] 是否收到过至少一帧合法数据（"开机以来是否通过话"）。
  // [解析] 返回 true 只代表曾经收到过，不代表现在还在线，判在线请用 is_alive()。
  bool is_open() const;
  // [解析] 是否"还活着"：曾经收到过 && 距今未超过 2000ms。
  // [解析] 参数 now_ms 传当前毫秒数（HAL_GetTick()）。返回值 true = 遥控器在线。
  // [解析] 2000ms 这个阈值很宽松，是为了容忍遥控器偶尔的丢包/卡顿。
  bool is_alive(uint32_t now_ms) const;

private:
  // [解析] 记住本对象管的是哪一路串口（&huart3 等），所有 HAL_UARTxxx 都要把它当第一个参数。
  UART_HandleTypeDef * huart_;
  // [解析] 是否使用 DMA 接收，决定 request() 走哪条分支。
  bool use_dma_;
  // [解析] 是否已经收到过合法帧，is_open() 直接返回它。
  bool has_read_;
  // [解析] 最近一次成功解析的时间戳（单位 ms），is_alive() 用它算"多久没收到数据了"。
  uint32_t last_read_ms_;
  // [解析] 接收缓冲区，DMA/中断直接把串口字节灌到这里；大小 50 字节见 VT02_BUFF_SIZE。
  // [解析] 注意它由中断上下文写入、由 update() 读取，本质上存在竞争，
  // [解析]   只是因为 update() 也是在中断里调用，才没有真正出事。
  uint8_t buff_[VT02_BUFF_SIZE];
};

