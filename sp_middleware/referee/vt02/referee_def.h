// [解析] 一帧裁判系统数据的完整排版（以自定义控制器数据 0x0302 为例）：
// [解析]   下标:  0      1    2      3     4   |  5      6    | 7 ... 7+data_len-1 | 倒数2 倒数1
// [解析]   内容: 0xA5  len低 len高  seq  crc8 | cmd低  cmd高  |   真正的数据段      |    CRC16
// [解析]         \______ 帧头 5 字节 ______/   \_ 命令码 2 字节 _/  \__ 数据段 __/     \_ 帧尾 2 字节 _/
// [解析] 注意：len 只统计"数据段"的长度，不含帧头、命令码和帧尾。

// [解析] 帧头长度 = SOF(1) + data_len(2) + seq(1) + crc8(1) = 5 字节。
// [解析] 之所以要单独定义，是因为 check_crc8() 只校验这 5 个字节。
// [解析] 命令码（cmd_id）占 2 字节，位于帧头之后、数据段之前。
// [解析] 帧尾就是 2 字节的 CRC16 校验码，它覆盖"从帧头第 0 字节到数据段最后一字节"。

// [解析] SOF = Start Of Frame，帧的起始标志。
// [解析] 0xA5 是裁判系统协议的固定帧头，收到一帧先看 buff_[0] 是不是 0xA5，
// [解析] 不是就直接丢弃（说明数据错位或是噪声），这是最省事的"对齐"手段。

// [解析] 0x0302：自定义控制器（也就是 VT02 图传遥控器）与机器人交互数据。
// [解析] 对应 referee_protocol.hpp 里的 cmd_id::CUSTOM_ROBOT_DATA。
// [解析] VT02 里的摇杆、拨轮、自定义按键就是从这个命令码的帧里解出来的。
// [解析] 0x0304：鼠标 + 键盘数据。
// [解析] 注意：vt02.cpp 的 update() 目前**只处理了 0x0302**，并没有用到这个宏，
// [解析]   所以 VT02 对象的 mouse / keys 成员实际上一直保持默认值，不会被填充。

// [解析] 数据段的起始下标 = 帧头 5 字节 + 命令码 2 字节 = 7。
// [解析] 所以 memcpy 时源地址写成 buff_ + REFEREE_DATA_START 就能直接对上结构体首成员。
// [解析] 这个 7 和 referee_protocol.hpp 里的 DATA_START 含义完全一致，
// [解析]   只是这边是老文件、用的是手写常量 7。

#define REFEREE_HEAD_LEN 5
#define REFEREE_CMD_ID_LEN 2
#define REFEREE_TAIL_LEN 2

#define REFEREE_SOF 0xA5

#define REFEREE_CUSTOM_CMD_ID 0x302
#define REFEREE_MOUSE_AND_KEYS_CMD_ID 0x304

#define REFEREE_DATA_START 7

#endif  // SP__REFEREE_DEF_H