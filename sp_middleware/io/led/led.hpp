// [解析] 【作用】把『板载 RGB 灯』封装成一个 LED 对象：调用 set(r, g, b) 就能改颜色和亮度。
// [解析] 【原理】灯的 R/G/B 三个脚分别接在同一个定时器的 3 个 PWM 通道上，
// [解析]         所以亮度其实是靠 PWM 占空比调出来的（占空比越大越亮）。
// [解析] 【被谁用】applications/ 下负责状态指示的任务，例如 sp::LED led(&htim5); led.start(); led.set(1,0,0);
// [解析] 【关键点】set() 的入参是 [0,1] 的浮点亮度，不是 0~255 的整数！
// [解析]         而且三个通道的对应关系是『通道1=B、通道2=G、通道3=R』，很容易接错看错（见 led.cpp）。
// [解析] ==========================================================================
#ifndef SP__LED_HPP
#define SP__LED_HPP

#include "tim.h"

namespace sp
{
// [解析] LED 类：一个对象管理一组三色灯（占用一个定时器的 CH1/CH2/CH3 三个通道）。
// [解析] 注意：set() 会改这个定时器的 ARR（重装值），所以该定时器的其他通道不要再做别的用途。
class LED
{
public:
  // [解析] ↑ 构造函数只保存定时器句柄，不点灯；构造后还要调用 start() 打开 3 个通道的 PWM。
  // [解析]   htim：CubeMX 生成的定时器句柄（如 &htim5），三个灯脚都挂在这个定时器上。
  LED(TIM_HandleTypeDef * htim);

  // [解析] ↑ 一次性启动该定时器的 3 个 PWM 通道（内部连调 3 次 HAL_TIM_PWM_Start）。
  // [解析]   不调用 start() 直接 set() 是不会有任何灯亮的。
  void start();

  // 取值范围: [0, 1]
  // [解析] ↑ 设置三色亮度：r/g/b 取值范围都是 [0, 1] 的浮点（0=灭，1=最亮）。
  // [解析]   例：set(1.0f, 0.0f, 0.0f) 是纯红，set(0.5f, 0.5f, 0.5f) 是半亮白色。
  // [解析]   注意：亮度看起来并不是线性的（人眼对亮度近似对数感觉），
  // [解析]   所以想让灯看起来『一半亮』，通常要填 0.2 左右而不是 0.5。
  // [解析]   副作用：每一帧都会重写 ARR 和 3 个 CCR 寄存器。
  void set(float r, float g, float b);

private:
  // [解析] ↑ 本对象控制的定时器句柄，R/G/B 三个通道都属于它。
  TIM_HandleTypeDef * htim_;
};

}  // namespace sp

#endif  // SP__LED_HPP