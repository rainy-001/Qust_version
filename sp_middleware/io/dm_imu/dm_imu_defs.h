#ifndef SP__DM_IMU_DEFS_H
#define SP__DM_IMU_DEFS_H

// ==================== DM-IMU-L1 寄存器地址 ====================
// [解析] 上面这行是原作者的分区标题，下面按"只读/只写/读写"三组列出所有寄存器编号。
// [解析] 这些编号用在两个地方：
// [解析]   1) 发请求时填进请求帧的第 2 字节（见 DM_IMU::write_request()）；
// [解析]   2) 收应答时用来判断"这包数据是什么"（见 DM_IMU::read() 的 switch(data[0])）。

// --- 数据读取寄存器 (只读 R) ---
// [解析] 下面 4 个是"只读寄存器"：你只能请求读它，不能往里写东西。
// [解析]   每个编号都对应一整包 8 字节的应答数据，解析代码在 dm_imu.cpp 的 read() 里一一对应。
#define DM_IMU_REG_ACCEL 0x01  // 加速度数据
// [解析] ↑ 0x01：三轴加速度 + 芯片温度。这是唯一带温度的一包（温度在 data[1]）。
#define DM_IMU_REG_GYRO 0x02   // 角速度数据
// [解析] ↑ 0x02：三轴角速度，单位 rad/s（不是 °/s，用的时候注意）。
#define DM_IMU_REG_EULER 0x03  // 欧拉角数据
// [解析] ↑ 0x03：欧拉角，单位"度"，顺序是 pitch、yaw、roll（和常见顺序不同）。
#define DM_IMU_REG_QUAT 0x04   // 四元数数据
// [解析] ↑ 0x04：姿态四元数 w,x,y,z，每个分量用 14 位压缩在 7 个字节里。

// --- 系统/控制寄存器 (只写 W) ---
// [解析] 下面这组是"命令型寄存器"：写进去就执行一个动作（比如重启、校准），没有数据可读。
// [解析]   注意：dm_imu.cpp 里的 write_request() 目前只会填"操作类型=0x00(读)"，
// [解析]   所以想用下面这些命令，还得自己把请求帧的第 3 字节改成写操作、并把参数放进 data[3..]。
#define DM_IMU_REG_RESTART 0x00        // 重启 IMU
// [解析] ↑ 0x00：让 IMU 软复位。注意它的编号是 0，和"没有寄存器"容易混淆，但确实是合法的命令。
#define DM_IMU_REG_ZERO_ANGLE 0x05     // 角度置零 (将当前姿态设为零点)
// [解析] ↑ 0x05：★ 最常用的一个命令。执行后"当前朝向"就变成 yaw = 0 的基准方向，
// [解析]   比赛前把车摆正、发这条命令，后面所有 yaw 就都是相对这个方向的转角了。
#define DM_IMU_REG_CALIB_ACC 0x06      // 启动加计六面校准
// [解析] ↑ 0x06：加速度计校准，需要把 IMU 依次按 6 个面静止放置，耗时较长，出厂前才做。
#define DM_IMU_REG_CALIB_GYRO 0x07     // 启动陀螺静态校准
// [解析] ↑ 0x07：陀螺仪零偏校准。执行时**必须保持静止**，否则会把运动当成零偏记下来，
// [解析]   之后解算出来的角度会一直往一个方向漂。
#define DM_IMU_REG_CALIB_MAG 0x08      // 启动磁计椭球校准
// [解析] ↑ 0x08：磁力计校准，需要拿着传感器在空间里画 8 字，用来消除磁干扰（yaw 靠它才不漂）。
#define DM_IMU_REG_SAVE_PARAM 0xFE     // 保存参数 (掉电不丢失)
// [解析] ↑ 0xFE：把上面校准得到的参数写进 IMU 内部 Flash。不执行这一步，下次断电就白校了。
#define DM_IMU_REG_FACTORY_RESET 0xFF  // 恢复出厂设置
// [解析] ↑ 0xFF：清掉所有参数回到出厂状态。校准乱了、怎么也调不好时的"最后手段"。

// --- 通信/配置寄存器 (读写 RW) ---
// [解析] 这组既能读回当前配置、也能写入新配置。
// [解析] ⚠ 这几个寄存器都是"改了以后影响通信本身"的（比如改 ID 之后你就得换 ID 去找它了），
// [解析]   改之前一定先想清楚怎么改回来，改错了就只能靠恢复出厂或专用上位机软件救。
#define DM_IMU_REG_COMM_MODE 0x09    // 切换通信模式
// [解析] ↑ 0x09：在 CAN / 串口等不同通信方式之间切换。
#define DM_IMU_REG_AUTO_RATE 0x0A    // 设置主动发送间隔
// [解析] ↑ 0x0A：设成非 0 后 IMU 会自己周期性地推数据（被动改主动），
// [解析]   就不需要 MCU 每次发请求了 —— 能省一半总线带宽和中断。
#define DM_IMU_REG_MODE_SWITCH 0x0B  // 切换主被动模式
// [解析] ↑ 0x0B：选择"主动上报"还是"被问才答"。本项目这个驱动是按"被动应答"写的。
#define DM_IMU_REG_BAUDRATE 0x0C     // 修改波特率
// [解析] ↑ 0x0C：改完之后 MCU 侧的波特率也必须同步改，否则立刻失联。
#define DM_IMU_REG_CAN_ID 0x0D       // CAN ID (接收ID)
// [解析] ↑ 0x0D：就是 dm_imu.hpp 构造函数里的 tx_id —— IMU 用它**接收**命令，
// [解析]   所以你发请求时目标 ID 要填这个值。
#define DM_IMU_REG_MST_ID 0x0E       // MST ID (发送ID)
// [解析] ↑ 0x0E：就是 dm_imu.hpp 构造函数里的 rx_id —— IMU 用它**发送**应答，
// [解析]   所以你在 CAN 回调里要判断收到的帧 ID 是不是等于这个值。
#define DM_IMU_REG_OUT_SELECT 0x0F   // 输出数据选择 (注:当前固件不支持修改)
// [解析] ↑ 0x0F：原注释已说明"当前固件不支持修改"，所以别指望用它挑数据内容，
// [解析]   老老实实按寄存器一个一个请求就好（这也是本驱动 read() 用 switch 的原因）。

// ==================== 数据解析线性映射极值 ====================
// (同之前，保持不变)
// [解析] 上面那行"保持不变"是原作者的备注，意思是这几个数值是沿用之前的定义，不要动。
// [解析] ★ 下面这 12 个宏的用法完全一致：它们是 dm_imu.cpp 里
// [解析]   uint_to_float(原始值, MIN, MAX, bits) 的前两个端点参数。
// [解析]   含义是"原始整数 0 对应 MIN，原始整数满量程(2^bits - 1)对应 MAX"，
// [解析]   中间的值按比例线性插值。所以这些数不是"随便定的量程"，而是官方协议规定的映射端点。
// [解析] ⚠ 数值后面都带 f 后缀（如 235.2f），表示它是 float 字面量。
// [解析]   如果不写 f，C++ 会把它当成 double，在做浮点乘法时会先转成双精度再算回来，
// [解析]   在 F407 这种没有硬件双精度浮点的芯片上会白白慢好几倍。养成写 f 的习惯。
#define DM_IMU_ACCEL_MAX (235.2f)
// [解析] ↑ 加速度量程上限：+235.2 m/s^2。235.2 = 24 × 9.8，也就是 ±24g 的加速度计原始量程。
// [解析]   代价是分辨率较粗（约 0.0072 m/s^2 一格），好处是不会因为撞击/震动轻易饱和。
#define DM_IMU_ACCEL_MIN (-235.2f)
// [解析] ↑ 加速度量程下限 -235.2 m/s^2，和上限对称，所以原始值的中位(约 32767)对应 0。
#define DM_IMU_GYRO_MAX (34.88f)
// [解析] ↑ 角速度量程上限：+34.88 rad/s。换算成角度是 34.88 × 180/π ≈ 1998.6 °/s，
// [解析]   也就是陀螺仪常见的 ±2000°/s 量程。注意单位是弧度，和欧拉角的"度"不是一套。
#define DM_IMU_GYRO_MIN (-34.88f)
// [解析] ↑ 角速度量程下限。全速旋转时角速度可能到几十 rad/s，所以这个量程是必要的。
#define DM_IMU_PITCH_MAX (90.0f)
// [解析] ↑ 俯仰角上限 +90°。只能到 90° 是因为欧拉角表示法在 90° 处有奇点(万向锁)，
// [解析]   厂家把 pitch 限制在 ±90° 内回避这个问题。
#define DM_IMU_PITCH_MIN (-90.0f)
// [解析] ↑ 俯仰角下限 -90°（机头朝正下方）。
#define DM_IMU_ROLL_MAX (180.0f)
// [解析] ↑ 横滚角上限 +180°。滚转可以转满一圈，所以量程比 pitch 大一倍。
#define DM_IMU_ROLL_MIN (-180.0f)
// [解析] ↑ 横滚角下限 -180°。
#define DM_IMU_YAW_MAX (180.0f)
// [解析] ↑ 偏航角上限 +180°。★ 注意 yaw 是"累加会绕回"的：
// [解析]   转到 +180° 再转一点就跳到 -180°，做角度控制时一定要处理这个"跨越 ±180"的问题，
// [解析]   否则误差会突然从 1° 变成 359° 导致机器人乱转。
#define DM_IMU_YAW_MIN (-180.0f)
// [解析] ↑ 偏航角下限 -180°。
#define DM_IMU_QUAT_MAX (1.0f)
// [解析] ↑ 四元数分量的上限 +1（四元数是"单位四元数"，每个分量都在 [-1, 1] 内）。
#define DM_IMU_QUAT_MIN (-1.0f)
// [解析] ↑ 四元数分量的下限 -1。
// [解析]   注意四元数换算时 uint_to_float 的 bits 参数传的是 14（不是 16），
// [解析]   因为协议里每个分量只占 14 位（见 dm_imu.cpp 的 QUAT 分支）。
// [解析] 小提醒：这 12 个宏大多是"成对"出现的 MIN/MAX，但并没有防呆检查，
// [解析]   如果哪天有人只改了 MAX 忘了改 MIN，映射出来的零点就会偏 —— 改的时候注意成对修改。

#endif  // SP__DM_IMU_DEFS_H