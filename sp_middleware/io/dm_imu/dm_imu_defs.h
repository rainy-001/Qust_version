// [解析]         让 dm_imu.cpp 里不用出现 0x01、235.2f 这种看不懂来历的"魔法数字"。
// [解析] 【被谁用】sp_middleware/io/dm_imu/dm_imu.hpp 和 dm_imu.cpp 都 include 它。
// [解析] 【内容分两半】
// [解析]   上半：寄存器地址（0x01 是加速度、0x04 是四元数……），是"我要问 IMU 要什么数据"的编号；
// [解析]   下半：量程极值（±235.2、±34.88……），是"原始整数要按什么比例换算成物理量"的两端。
// [解析] 【关键点】下半那堆极值必须和上半的寄存器一一对应着看：它们就是 dm_imu.cpp 里
// [解析]         uint_to_float(x, MIN, MAX, bits) 的第 2、3 个实参。
