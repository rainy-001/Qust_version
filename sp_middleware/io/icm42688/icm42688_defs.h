// [解析] ==========================================================================
// [解析] 【文件】sp_middleware/io/icm42688/icm42688_defs.h
// [解析] 【作用】ICM42688 的"寄存器字典"：寄存器地址、配置值的位编码、错误码，都用宏命名。
// [解析]         本身只有 #define，不生成任何机器码，只是让代码里不再出现裸数字。
// [解析] 【被谁用】icm42688.cpp（配置芯片、读写数据、判断初始化结果）。
// [解析] 【关键点】1) 量程宏是"(编码 << 5)"，因为量程字段位于配置寄存器的 bit[7:5]；
// [解析]             而 ODR 宏是未移位的裸编码，占据 bit[3:0]。两者按位或即成一个字节。
// [解析]           2) "16G" 的编码是 0x00、"2G" 的编码是 0x03 —— 量程越大编码越小，
// [解析]             和 BMI088 的加速度计正好相反，别记混。
// [解析]           3) 0x0F 表示低噪声模式，是加速度计和陀螺仪两个 2 位字段都置 11 的结果。
// [解析] ==========================================================================

#ifndef ICM42688_DEFS_H
#define ICM42688_DEFS_H

// ICM42688 寄存器地址及其存放的内容
// [解析] DEVICE_CONFIG：器件通用配置寄存器，写 0x01 这个固定"魔数"就触发软复位。
// [解析] 复位后所有寄存器回到默认值，配置表需要重新写。
#define ICM42688_DEVICE_CONFIG 0x11
#define ICM42688_SOFT_RESET_VALUE 0x01

// [解析] PWR_MGMT0：电源管理寄存器，必须最先配置好，否则量程等寄存器写了也不生效。
// [解析] 取值 0x0F 的二进制是 0000_1111：
// [解析]   bit[1:0] = 11 —— 加速度计进入低噪声(Low Noise)模式（比低功耗模式噪声小）；
// [解析]   bit[3:2] = 11 —— 陀螺仪同样进入低噪声模式；
// [解析]   高 4 位为 0 —— 温度传感器不禁用、其他保留位保持默认。
// [解析] 想省电可以改成低功耗模式，但姿态解算的精度会下降。
#define ICM42688_PWR_MGMT0 0x4E
#define ICM42688_PWR_LN_MODE 0x0F // 加速度计和陀螺仪开启低噪声模式 (Low Noise Mode)

// [解析] WHO_AM_I：只读的"身份证"寄存器，任何写入都无效，读出来永远是 0x47。
// [解析] 初始化时用它判断"芯片到底在不在总线上"。
#define ICM42688_WHO_AM_I 0x75
#define ICM42688_CHIP_ID_VALUE 0x47

// 寄存器配置宏
// [解析] ACCEL_CONFIG0 / GYRO_CONFIG0 是"量程 + 输出速率"的配置寄存器，两个寄存器布局相同：
// [解析]   bit[7:5] 量程档位，bit[4] 保留（写 0），bit[3:0] 输出速率 ODR。
// [解析] 所以初始化表里写的是 ACC_RANGE_SET | ODR_SET —— 一个管高位、一个管低位，按位或拼起来。
#define ICM42688_ACCEL_CONFIG0 0x50
#define ICM42688_GYRO_CONFIG0 0x4F

// 量程设置宏 (位移已经计算好，直接或运算即可)
// [解析] ★为什么要 << 5★ 量程字段在 bit[7:5]，所以编码值必须左移 5 位才能落到正确位置。
// [解析] 以加速度为例：写 0x00 是 ±16g，写 0x20(=1<<5) 是 ±8g，写 0x40(=2<<5) 是 ±4g，
// [解析] 写 0x60(=3<<5) 是 ±2g。注意"量程越大编码越小"，而且量程越小分辨率越高。
// [解析] icm42688.cpp 用的是 16G，因为 1 LSB 对应的加速度变化量已经足够小，
// [解析] 同时又能扛住机器人的落地冲击而不削顶。
#define ICM42688_ACC_RANGE_16G (0x00 << 5)
#define ICM42688_ACC_RANGE_8G  (0x01 << 5)
#define ICM42688_ACC_RANGE_4G  (0x02 << 5)
#define ICM42688_ACC_RANGE_2G  (0x03 << 5)

// [解析] 陀螺仪量程同理，同样左移 5 位：2000dps 编码 0，250dps 编码 3。
// [解析] 2000dps 意味着满量程 ±2000°/s，1 LSB = 2000/32768 ≈ 0.061 °/s。
#define ICM42688_GYRO_RANGE_2000DPS (0x00 << 5)
#define ICM42688_GYRO_RANGE_1000DPS (0x01 << 5)
#define ICM42688_GYRO_RANGE_500DPS  (0x02 << 5)
#define ICM42688_GYRO_RANGE_250DPS  (0x03 << 5)

// 输出速率 ODR (Output Data Rate)
// [解析] ODR = 芯片每秒产生多少个新数据。字段在 bit[3:0]，所以这些宏不需要移位，直接或进去。
// [解析] 本项目用 0x06 = 1kHz，对应"1ms 出一次新数据"，也就是周期任务按 1kHz 调用 update() 最合适。
// [解析] 注意 0x01 表示 32kHz（最高速），编码越大速率越低，和量程的规律相反。
#define ICM42688_ODR_32KHZ 0x01
#define ICM42688_ODR_16KHZ 0x02
#define ICM42688_ODR_8KHZ  0x03
#define ICM42688_ODR_4KHZ  0x04
#define ICM42688_ODR_2KHZ  0x05
#define ICM42688_ODR_1KHZ  0x06  // 我们采用 1000Hz 满足要求
#define ICM42688_ODR_200HZ 0x07

// 数据寄存器起始地址 (突发读取起始点)
// [解析] 从 0x1D 开始，地址连续递增的数据寄存器一共 14 个字节，顺序是：
// [解析]   温度(0x1D~0x1E) -> 加速度 XYZ(0x1F~0x24) -> 角速度 XYZ(0x25~0x2A)。
// [解析] 所以 update() 里只要 read_registers(0x1D, 14) 一次就能把全部数据抓回来。
// [解析] 这种连续读法叫"突发读取(burst read)"，比对每个寄存器单独读快得多，
// [解析] 而且能保证 7 个量来自同一个采样时刻（否则各轴数据可能跨采样点，解算会抖）。
#define ICM42688_TEMP_DATA1 0x1D

// ICM42688 错误码
// [解析] device_init() 的返回值就是下面这些：0 表示全部配置成功。
// [解析] 每个错误码对应配置表里某一步"写进去但读回来不一样"，把它打印出来就能定位问题。
// [解析] 另外提醒：有些寄存器读回的值可能和写入值不完全相同（夹带状态位），
// [解析]   那时就不能简单用 != 判断；本驱动选用的寄存器恰好都能原样读回，所以这样写是安全的。
#define ICM42688_NO_ERROR 0x00
#define ICM42688_PWR_MGMT_ERROR 0x01
#define ICM42688_ACCEL_CONF_ERROR 0x02
#define ICM42688_GYRO_CONF_ERROR 0x03
// [解析] 0xFF 特指"WHO_AM_I 读到的不是 0x47"，也就是芯片不在线（没焊/接线错/SPI 配置错）。
#define ICM42688_NO_SENSOR 0xFF

// [解析] 头文件结束。include guard（#ifndef/#define/#endif 三件套）的作用是：
// [解析] 防止同一个头文件被重复 include 时宏被定义两次（会报 warning 甚至编译错误）。
#endif  // ICM42688_DEFS_H