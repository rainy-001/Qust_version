#include "servo.hpp"

namespace sp
{
// [解析] 构造函数：只把 4 个参数存进成员变量，函数体为空 —— 不动硬件、不输出波形。
Servo::Servo(TIM_HandleTypeDef * htim, uint16_t channel, float clock_hz, float max_angle)
: htim_(htim), channel_(channel), clock_hz_(clock_hz), max_angle_(max_angle)
{
}

void Servo::start()
{
  // [解析] ↑ 让这个通道开始输出 PWM。此时脉宽还是 CubeMX 配的默认值，要调用 set() 才会到你想要的角度。
  // [解析]   dismiss return 是本项目约定：故意不检查 HAL 返回值，看到它就知道不是漏写判断。
  HAL_TIM_PWM_Start(htim_, channel_);  // dismiss return
}

// [解析] set()：把角度换算成舵机需要的 PWM 参数。整个过程分三步：
// [解析]   1) 把计数时钟降到 1MHz，让『1 个计数 = 1 微秒』；
// [解析]   2) 把周期设成 20000 个计数 = 20000us = 20ms，也就是 50Hz；
// [解析]   3) 把脉宽设成 500us + 角度比例 × 2000us，落在 [500, 2500]us 区间。
void Servo::set(float angle)
{
  // [解析] ↑ 1e6f 就是 1000000.0f（1MHz）。原理：计数频率 = 输入时钟 / (PSC + 1)，
  // [解析]   要让计数频率等于 1MHz，就取 PSC = clock_hz / 1e6 - 1。
  // [解析]   例：clock_hz = 84MHz 时 PSC = 84 - 1 = 83。
  // [解析]   这样做的意义：后面写 ARR 和 CCR 时，数字可以直接当成微秒数，不用反复换算。
  // [解析]   注意：这是浮点运算后隐式转成 16 位整数（截断），输入时钟不是 1MHz 整数倍时有小误差；
  // [解析]   另外舵机的角度精度只取决于脉宽分辨率（1 个计数 = 1us），1us 已经足够细了。
  __HAL_TIM_SET_PRESCALER(htim_, clock_hz_ / 1e6f - 1);                       // 预分频后为1MHz
  // [解析] ↑ ARR = 20000 - 1 = 19999：计数器从 0 数到 19999 是一轮，共 20000 个计数。
  // [解析]   因为 1 个计数 = 1us，所以一轮 = 20000us = 20ms，频率 = 1/20ms = 50Hz。
  // [解析]   为什么要是 50Hz：这是绝大多数模拟舵机的标准控制信号频率，
  // [解析]   低于/高于这个频率很多时舵机会抖动甚至不响应。
  __HAL_TIM_SET_AUTORELOAD(htim_, 20000 - 1);                                 // 输出频率为50Hz
  // [解析] ↑ 这一行是『角度 -> 脉宽』的换算公式，拆开看：
  // [解析]   angle / max_angle_：先把角度归一化成 0~1 的比例（0 度 -> 0，满角度 -> 1）；
  // [解析]   再乘 2000：把比例映射成 0~2000us 的额外脉宽；
  // [解析]   最后加 500：起点是 500us（0.5ms），所以总脉宽落在 [500, 2500]us。
  // [解析]   例：max_angle=180、angle=90 时，CCR = 0.5×2000 + 500 = 1500us，正好是中位。
  // [解析]   注意 1：公式里写死 2000 和 500，等于假定『0.5ms~2.5ms 对应 0~max_angle 度』。
  // [解析]   如果你的舵机行程不一样（比如有些 270 度舵机其实是 0.5ms~2.5ms 对应 0~270 度），
  // [解析]   只要 max_angle 填对，这个线性比例仍然成立；但如果舵机手册的脉宽范围不是 500~2500us，
  // [解析]   就要改这两个常数（属于驱动作者写死的经验值）。
  // [解析]   注意 2：angle 超范围时这里不做裁剪，会输出超范围的脉宽，可能让舵机堵转，调用者要自己限制。
  __HAL_TIM_SET_COMPARE(htim_, channel_, (angle / max_angle_) * 2000 + 500);  // [500, 2500]
}

}  // namespace sp