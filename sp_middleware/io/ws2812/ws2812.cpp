// [解析] 【文件】sp_middleware/io/ws2812/ws2812.cpp
// [解析] 【作用】ws2812.hpp 的实现：把 r/g/b 三个字节编码成 24 字节 SPI 码流发出去。
// [解析] 【被谁用】applications/ 下的灯效任务，通过 WS2812 对象调用 set()。
// [解析] 【原理】线上一个 WS2812 位只占 4 个 SPI 位，而 SPI 一个字节有 8 位，
// [解析]         所以『一个字节能承载两个 WS2812 位』；本文件把每个字节的前半段拿来当一位用，
// [解析]         靠 0xC0 与 0xF0 产生长短不同的高电平，从而区分 0 和 1。
// [解析] 【关键点】1) CODE0/CODE1 这两个魔数怎么来的；2) >> i 与 & 0x01 是逐位取二进制；
// [解析]           3) buff_[07 - i] 这种倒着填是为了凑『高位先发』的顺序。
// [解析] ==========================================================================
#include "ws2812.hpp"

namespace sp
{
// [解析] ↑ WS2812 的『0』码，二进制 1100 0000。
// [解析]   为什么是它：WS2812 靠高电平的长短区分 0/1，SPI 发一个字节时先送最高位，
// [解析]   所以字节的高位段就是最先出现在 MOSI 线上的电平。0xC0 的高两位是 1，
// [解析]   输出来的是一段『较短』的高电平，正好对应 WS2812 的 0 码。
// [解析]   注意：它到底对应多少纳秒，取决于 SPI 的波特率与时钟极性/相位配置，属于硬件层的坑；
// [解析]   本文件只负责生成码形，真正的时序要靠 CubeMX 里配好的 SPI 参数保证。
constexpr uint8_t CODE0 = 0xC0;
// [解析] ↑ WS2812 的『1』码，二进制 1111 0000。
// [解析]   高四位是 1，所以 SPI 先输出一段『较长』的高电平，对应 WS2812 的 1 码。
// [解析]   0xF0 与 0xC0 的区别只有那个高电平段的长度，这就是整个驱动最核心的思路。
constexpr uint8_t CODE1 = 0xF0;

// [解析] 构造函数：只保存 SPI 句柄，函数体为空 —— 不配置 SPI、也不发送数据，动作都在 set() 里。
WS2812::WS2812(SPI_HandleTypeDef * hspi) : hspi_(hspi) {}

// [解析] set()：把颜色编码进 buff_ 并立刻通过 SPI 发出去（阻塞式，发完才返回）。
// [解析] 参数 r/g/b 都是 0~255（红/绿/蓝亮度），0 是全灭、255 是最亮。
void WS2812::set(uint8_t r, uint8_t g, uint8_t b)
{
  // [解析] 循环 8 次，每次处理每个颜色的 1 个二进制位，8 次正好覆盖一个字节的 8 位。
  for (int i = 0; i < 8; i++) {
    // [解析] i=0 处理最低位（LSB），i=7 处理最高位（MSB），所以这个循环是在逐位拆字节。
    // [解析] ↑ 一行里干了好几件事，以绿色 g 为例拆开看：
    // [解析]   1) (g >> i) & 0x01：把 g 右移 i 位再和 1 相与，等价于『取出 g 的第 i 位』，结果非 0 即 1；
    // [解析]   2) ? CODE1 : CODE0：这一位是 1 就选长高电平码 0xF0，是 0 就选短高电平码 0xC0；
    // [解析]   3) >> 1：把码整体右移一位（0xF0 变成 0x78、0xC0 变成 0x60），
    // [解析]      目的是让高电平段落在字节里更靠中间的位置，避开 SPI 帧边沿的不确定性；
    // [解析]   4) buff_[07 - i]：倒着存。i=0（最低位）写到最后面的 buff_[7]，i=7（最高位）写到 buff_[0]，
    buff_[07 - i] = (((g >> i) & 0x01) ? CODE1 : CODE0) >> 1;
    // [解析]      这样数组从前往后发出去时就变成 MSB 先发，符合 WS2812『高位先出』的规定。
    // [解析]   小提示：07 是八进制字面量，值就是 7，和写 7 完全等价，属于作者的书写习惯。
    // [解析] ↑ 处理绿色之后紧接着处理红色 r，结果放在 buff_[8..15]。
    // [解析]   注意下标是 15-i：i=7（最高位）落在 buff_[8]，i=0 落在 buff_[15]，同样保证高位先发。
    buff_[15 - i] = (((r >> i) & 0x01) ? CODE1 : CODE0) >> 1;
    // [解析] ↑ 最后处理蓝色 b，结果放在 buff_[16..23]（i=7 对应 buff_[16]，i=0 对应 buff_[23]）。
    buff_[23 - i] = (((b >> i) & 0x01) ? CODE1 : CODE0) >> 1;
    // [解析]   三个颜色的发送先后是 G、R、B —— 这正是 WS2812 芯片规定的 GRB 色序，
    // [解析]   所以调用者按 set(r,g,b) 的直觉顺序传参即可，驱动内部已经帮你排好序了。
  }

  // [解析] ↑ 把 24 字节码流一次性发出去：参数依次是 SPI 句柄、缓冲区、字节数 24、超时 0xFFFF。
  // [解析]   0xFFFF 是超时时间，单位毫秒（约 65.5 秒），实际等于死等；它是阻塞式发送，
  // [解析]   24 字节很短，但仍然不建议在中断里调用。
  // [解析]   末尾的 dismiss return 是本项目写法约定：故意不检查 HAL 返回值，看到它就知道不是漏写判断。
  // [解析]   注意 1：发送长度 24 与 buff_ 的大小一致（3 个颜色乘 8 位），不会越界。
  // [解析]   注意 2：本实现只支持一颗灯珠，也没有发送 WS2812 需要的复位/锁存间隔（大于 50us 的低电平）；
  // [解析]   若灯带有多颗灯珠或需要刷新显示，这里要按灯珠数扩展缓冲并补上复位间隔。
  HAL_SPI_Transmit(hspi_, buff_, 24, 0xFFFF);  // dismiss return
}

}  // namespace sp
