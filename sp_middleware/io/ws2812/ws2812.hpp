// [解析] 【作用】驱动 WS2812/WS2812B 这类『单总线可编程 RGB 灯珠』。
// [解析] 【原理】WS2812 没有时钟线，它靠『高电平持续时间的长短』来区分 0 和 1，
// [解析]         时序要求很严格（几百纳秒级），软件翻转 IO 很难稳定做到，
// [解析]         所以这里用 SPI 的 MOSI 引脚去模拟：一个 WS2812 位用 4 个 SPI 位表示。
// [解析] 【被谁用】applications/ 下的灯效任务，例如 sp::WS2812 led(&hspi1); led.set(255, 0, 0);
// [解析] 【关键点】1) 颜色要填 0~255 的整数（和 led.hpp 的 [0,1] 浮点不一样！）；
// [解析]         2) 只有一颗灯珠的定长实现，且只发一次数据、不锁存刷新；
// [解析]         3) 真正的位编码在 ws2812.cpp 里，本文件只声明接口。
// [解析] ==========================================================================
#ifndef SP__WS2812_HPP
#define SP__WS2812_HPP

#include "spi.h"

namespace sp
{
// [解析] WS2812 类：一个对象对应 SPI 上挂的一条灯带（当前实现按 1 颗灯计算，见 buff_ 注释）。
// [解析] 注意：SPI 的波特率决定了输出码形是否符合 WS2812 时序，属于硬件/时钟树的坑。
class WS2812
{
public:
  // [解析] ↑ 构造函数只保存 SPI 句柄，不点灯也不发数据。
  // [解析]   hspi：CubeMX 生成的 SPI 句柄（如 &hspi1）；它的 MOSI 引脚接到灯珠的 DIN。
  WS2812(SPI_HandleTypeDef * hspi);
  // [解析] ↑ 设置这一颗灯珠的颜色：r/g/b 都是 0~255 的整数（0=不亮，255=最亮）。
  // [解析]   内部会把 3 个字节编码成 24 个字节的 SPI 码流并立即发送，
  // [解析]   发送是阻塞式的（超时 0xFFFF），所以别在中断里调用。
  // [解析]   注意：色序是 GRB 而不是 RGB，芯片说明书就是这么定义的（见 ws2812.cpp 的注释）。
  void set(uint8_t r, uint8_t g, uint8_t b);

private:
  // [解析] ↑ 本对象使用的 SPI 句柄，靠它把码流一位一位移出去。
  SPI_HandleTypeDef * hspi_;
  // [解析] ↑ 发送缓冲区：一颗灯珠 3 个颜色 × 8 位 = 24 个颜色位，而每个颜色位要用 1 个字节来编码，
  // [解析]   所以正好是 24 个字节（每字节只用一个 WS2812 位，高 3 位为高电平、其余为低电平）。
  // [解析]   它同时也是成员变量，好处是不用每次 set() 都在栈上开临时数组。
  uint8_t buff_[24];
};

}  // namespace sp

#endif  // SP__WS2812_HPP