// [解析]         功率/电压/温度/能量，以及把要下发的参数打包成 8 字节。
// [解析] 【被谁用】由 applications/vision_task.cpp 里的 sp::SuperCap supercap 对象调用。
// [解析] 【看代码的重点】三件事，看懂了这一个文件就全懂了：
// [解析]   1) 字节顺序：本模块反馈是【低字节在前】(小端)，和 rm_motor.cpp 里的电机
// [解析]      (高字节在前，大端)【正好相反】。这是新手最容易读错的地方。
// [解析]   2) 单位换算：功率要 /10，电压要 /100，少除一个 0 电压就会变成几百伏。
// [解析]   3) 能量是算出来的：cap_energy 不在 CAN 帧里，是用 E = 0.5*C*U^2 现算的。
// [解析] 【协议速查表】控制帧 0x300（我们发 → 模块收）：
// [解析]   data[0]    = 工作模式（SuperCapMode）
// [解析]   data[1..2] = 底盘功率上限 (uint16，高字节在 data[1])
// [解析]   data[3..4] = 保留
// [解析]   data[5..6] = 缓冲能量   (uint16，高字节在 data[5])
// [解析]   data[7]    = 底盘输出标志
// [解析]   反馈帧 0x301/0x302（模块发 → 我们收）：
// [解析]   data[0..1] = power_in  (int16，低字节在前)
// [解析]   data[2..3] = power_out (int16，低字节在前)
// [解析]   data[4..5] = voltage   (int16，低字节在前)
// [解析]   data[6]    = temperature
// [解析]   data[7]    = status
// [解析] ==========================================================================

#include "super_cap.hpp"

