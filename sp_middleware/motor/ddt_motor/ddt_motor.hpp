// [解析] 【文件】sp_middleware/motor/ddt_motor/ddt_motor.hpp
// [解析] 【作用】把"达妙(Damiao)DDT 系列电机"封装成一个类。
// [解析]         它的三个动作和 RM_Motor 完全一样，学会一个另一个就会了：
// [解析]           读反馈 read()  -> 得到 angle/speed/torque
// [解析]           下指令 cmd()   -> 指定输出力矩
// [解析]           打包 write()  -> 把指令写进 CAN 的 8 字节缓冲区
// [解析] 【被谁用】本仓库里暂时没有 applications/ 下的任务文件实例化 DDT_Motor，
// [解析]           它属于"备用的电机驱动"，给需要换用达妙电机的队伍直接用。
// [解析]           用法与 can_task.cpp 里的 RM_Motor 一模一样：
// [解析]             sp::DDT_Motor m(1, 0.36f);   // 1 号电机，力矩常数 0.36 N·m/A
// [解析]             m.cmd(0.5f); m.write(can1.tx_data); can1.send(m.tx_id);
// [解析]             if (can1.rx_id == m.rx_id) m.read(can1.rx_data);
// [解析] 【关键点】最容易错的三个地方：
// [解析]   1) 力矩常数 torque_const 是"每安培能出多少 N·m"，必须按你手上电机的型号填，
// [解析]      填错不会报错，只会让所有力矩都按比例偏大或偏小（闭环会振荡或没劲）。
// [解析]   2) 反馈里的角度是 16 位（0~65535）且被映射成 0~4*PI，再折回 (-PI, PI]，
// [解析]      所以它【不是】绝对多圈角度，一过 180 度就跳号，详见 ddt_motor.cpp。
// [解析]   3) 一帧同样只能装 4 台电机，1~4 号用 0x32、5~8 号用 0x33。
// [解析] ==========================================================================

#ifndef SP__DDT_MOTOR_HPP
#define SP__DDT_MOTOR_HPP

#include <cstdint>

namespace sp
{

// [解析] DDT_Motor：一个对象 = 总线上的一台达妙电机。
// [解析] 它没有减速比、也没有多圈累计这些概念，所以比 RM_Motor 简单不少。
class DDT_Motor
{
public:
  // [解析] 构造函数。
  // [解析]   motor_id    —— 电机 ID，取值 1~8。它同时决定收发帧 ID 和"占第几个字节位置"。
  // [解析]   torque_const —— 力矩常数 Kt，单位 N·m/A（每 1 安培电流能产生多大力矩）。
  // [解析]     取值来自达妙电机的手册/上位机参数，不同型号不同（常见 0.x 量级）。
  // [解析]     ★ 它是 read() 算力矩和 cmd() 反算电流的共同系数，填错会让读数与指令一起偏。
  // [解析] 副作用：只计算并保存 ID 和常数，不碰硬件、不发帧。
  DDT_Motor(uint8_t motor_id, float torque_const);

  const uint16_t rx_id;  // 电机反馈帧ID
  // [解析] ↑ 电机反馈帧的 ID，等于 0x96 + 电机ID（即 0x97~0x9E）。
  // [解析]   收到帧后拿 can1.rx_id 和它比较，相等才调 read()。
  const uint16_t tx_id;  // 电机控制帧ID
  // [解析] ↑ 我们发控制帧用的 ID：1~4 号电机用 0x32，5~8 号用 0x33。
  // [解析]   为什么分两组：一帧 8 字节、每台电机占 2 字节，所以一帧最多带 4 台。

  uint8_t error;  // 只读! 0x00: 无故障, 略
  // [解析] ↑ 只读、由 read() 更新，取自反馈帧第 6 字节。
  // [解析]   0x00 表示无故障；其他值的含义请查达妙手册。原注释写"略"，
  // [解析]   意思是作者没把故障码表抄过来，真出问题时要去翻手册。
  uint8_t mode;  // 只读! 0x00: 电压开环, 0x01: 电流环, 0x02: 速度环, 0x09: 失能模式, OxOA: 使能模式
  // [解析] ↑ 只读，反馈帧第 7 字节，告诉你"电机当前跑在哪种控制模式下"。
  // [解析]   ★ 原注释里的 "OxOA" 用的是字母 O 而不是数字 0，实际应当是 0x0A（= 10）。
  // [解析]     这是原注释的笔误，这里照原样保留，阅读时按 0x0A 理解即可。
  // [解析]   ★ 本类只实现了力矩（电流环）控制，所以真正要出力时
  // [解析]     电机的 mode 一般应当是 0x01 或 0x0A 这种"使能+电流环"状态。

  float angle = 0;   // 只读! 单位: rad
  // [解析] ↑ 只读，由 read() 更新。★ 注意它是"折回 (-PI, PI] 的单圈角度"，
  // [解析]   和你直观理解的"累计转了多少"不一样：转过 180° 后会从 +PI 跳到 -PI。
  // [解析]   要拿它做连续控制，请自己配一个 sp::AngleUnwrapper（见 math_tools.hpp）。
  float speed = 0;   // 只读! 单位: rad/s
  // [解析] ↑ 只读。电机反馈的转速经"rpm -> rad/s"换算后的值，可正可负表示转向。
  float torque = 0;  // 只读! 单位: N·m
  // [解析] ↑ 只读。由反馈电流乘以力矩常数 torque_const_ 得到，是"当前实际出力"的估计。

  // [解析] read()：解析一帧反馈（8 字节），更新 speed/torque/angle/error/mode。
  // [解析]   data —— 指向收到的 8 字节原始数据（通常是 can1.rx_data）。
  // [解析]     参数类型是 const uint8_t *，意思是"我只看不改"，比 RM_Motor 的版本更严谨。
  // [解析] ★ 因为本函数不记录时间戳，所以【没有】is_alive() 这类在线判断能力，
  // [解析]   如果需要掉线检测，你得自己在调用处记录时间。
  // [解析] 副作用：直接改写对象里的 5 个公开成员。
  void read(const uint8_t * data);
  // [解析] write()：把 cmd() 存下的指令写进 8 字节缓冲区 data 里属于本电机的那 2 个字节。
  // [解析]   data —— 通常是 can1.tx_data。
  // [解析] ★ 和 RM_Motor 一样：4 台电机各自 write() 进同一帧，最后统一 send() 一次。
  void write(uint8_t * data) const;

  // 单位: N·m
  // [解析] cmd()：设定期望输出力矩。
  // [解析]   value —— 力矩，单位 N·m，可正可负（正负决定转向）。
  // [解析]   内部会先除以力矩常数换成电流，再按 raw 量程限幅。
  // [解析]   副作用：只更新私有成员 cmd_raw_，必须再调 write() + can1.send() 才发出。
  void cmd(float value);

private:
  // [解析] ↓ 两个构造时定死的常量，加 const 防止被误改。
  const uint8_t motor_id_;
  // [解析] ↑ 记住 ID，write() 靠它算"我占哪 2 个字节"。
  const float torque_const_;
  // [解析] ↑ 力矩常数 N·m/A，read() 和 cmd() 都要用。
  int16_t cmd_raw_ = 0;
  // [解析] ↑ 换算后的指令（协议里的整数电流值），初值 0 = 不给力，安全。
  // [解析]   用类内初始化（= 0）而不是在构造函数初始化列表里赋值，效果等价、写法更省事。
};

}  // namespace sp

#endif  // SP__DDT_MOTOR_HPP