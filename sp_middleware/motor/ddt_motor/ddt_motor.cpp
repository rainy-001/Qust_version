// [解析]         以及把"想要的力矩"换算成驱动板认识的整数电流值。
// [解析] 【看代码的重点】先记住本文件里的两个"量纲换算"常量，其它都好懂：
// [解析]   DDT_MOTOR_MAX_RAW = 16383  —— 指令（电流值）的满量程。
// [解析]       注意是 16383 而不是 16384，因为要用它同时表示 +满和 -满，
// [解析]       取 2^14-1 才能保证取负之后仍在 int16 范围内、且正负对称。
// [解析]   DDT_MOTOR_RAW_TO_CURRENT = 55/32767 —— "raw -> 安培"的换算系数。
// [解析]       55 是这个系列驱动板能输出的最大电流（±55A），
// [解析]       32767 是 int16 的正半轴满量程，所以 1 个 raw ≈ 0.00168 A。
// [解析] 【协议速查表】反馈帧（大端序，高字节在前，和 RM_Motor 一样）：
// [解析]   data[0..1] = speed   (int16，单位 0.1 rpm)
// [解析]   data[2..3] = current (int16，单位 raw，要乘上面那个系数才变成安培)
// [解析]   data[4..5] = angle   (uint16，编码器原始值)
// [解析]   data[6]    = error（故障码）
// [解析]   data[7]    = mode （当前控制模式）
// [解析] 【重要提醒】本类【没有】记录时间戳，所以没有 is_alive() 掉线检测；
// [解析]   而且反馈角度算出来是"折回 (-PI, PI] 的单圈角度"，不是累计角度。
// [解析] ==========================================================================

#include "ddt_motor.hpp"

