// [解析] 【文件】sp_middleware/motor/rm_motor/rm_motor.hpp
// [解析] 【作用】把大疆 RoboMaster 官方电机（M2006 / M3508 / GM6020）封装成一个类：
// [解析]         上层只做三件事 —— motor.read() 拿反馈、motor.cmd() 下指令、motor.write() 打包。
// [解析] 【被谁用】applications/can_task.cpp：
// [解析]           sp::RM_Motor motor6020(1, sp::RM_Motors::GM6020_V);
// [解析]           然后在 can_task() 里 cmd()/write() 发指令，
// [解析]           在 HAL_CAN_RxFifo0MsgPendingCallback() 中断里 read() 收反馈。
// [解析]           另外 sp_middleware/tools/joint/joint_controller.cpp 里
// [解析]           显式实例化了 JointMotorController<sp::RM_Motor>，也就是关节控制器
// [解析]           把这套电机当"底层驱动"来用（读 angle/speed/torque，写 cmd）。
// [解析] 【背景知识】这些电机都是"CAN 总线上的智能驱动器"：你发一帧 8 字节的控制帧，
// [解析]             它在同一路总线上回一帧 8 字节的反馈帧，ID 由电机上的拨码开关决定。
// [解析] 【阅读顺序】先看本文件了解"类有哪些成员、单位是什么"，
// [解析]             再看 rm_motor.cpp 了解"原始数据怎么换算成物理量"。
// [解析] 【关键点】三个最容易卡住新手的地方（cpp 里有详细推导）：
// [解析]   1) 编码器 0~8191 怎么变成 -PI~PI 的弧度，以及"多圈"是怎么数出来的；
// [解析]   2) 不同型号电机的 raw 最大值、量纲换算系数完全不同；
// [解析]   3) 多个电机是"共用一帧 8 字节"的，所以 write() 只写属于自己那 2 个字节。
// [解析] ==========================================================================

#ifndef SP__RM_MOTOR_HPP
#define SP__RM_MOTOR_HPP

#include <cstdint>

namespace sp
{
// [解析] 下面两个是"减速箱减速比"，也就是电机转 ratio 圈，输出轴才转 1 圈。
// [解析] 为什么要用它：电机内部反馈的角度/转速是"转子侧"的，而我们要控制的是
// [解析] "输出轴侧"的量，所以读的时候要除以 ratio，写指令的时候要乘以 ratio。
constexpr float M2006_P36 = 36.0f;             // 原装减速箱减速比
// [解析] ↑ M2006 配 P36 减速箱：转子转 36 圈，输出轴转 1 圈。
constexpr float M3508_P19 = 3591.0f / 187.0f;  // 原装减速箱减速比
// [解析] ↑ M3508 配 P19 减速箱，官方给的真实减速比是 3591/187 ≈ 19.2032。
// [解析]   注意：这里没写成 19.0f，是因为 19 是"约等于"的宣传值，
// [解析]   真按 19.0 算，跑几十圈之后角度就会差出可见的偏差，所以必须用精确分数。

// [解析] ↓ 三个"最大力矩"常量（原注释标的单位是 N·m）。
// [解析]   0.18 / 0.3 / 0.741 三个数来自大疆官方手册里各型号的力矩标定值
// [解析]   （M2006 约 0.18、M3508 约 0.3、GM6020 约 0.741）。
// [解析]   后面的 *10 / *20 / *3 是原作者的额外放大系数，手册里并没有直接给出这三个倍数，
// [解析]   ★ 具体来历（是不是"整组多台电机的总力矩"）无法从代码和手册确证，属于来历不明的系数。
// [解析]   好消息是：rm_motor.cpp 里 read() 的力矩换算和 cmd() 的反算都带着同样的倍数，
// [解析]   所以"读回来的 torque"和"发出去的 cmd"口径是自洽的，闭环能用；
// [解析]   但它们的绝对值不能和手册上的 N·m 直接对账。
// [解析] ★ 建议：真要改这些系数时，把 hpp 这里的常量和 rm_motor.cpp 里的
// [解析]   XXX_RAW_TO_TORQUE / XXX_CMD_TO_RAW 一起核对，只改一处会让收发对不上。
constexpr float M2006_P36_MAX_TORQUE = 0.18f * 10;  // N·m
constexpr float M3508_P19_MAX_TORQUE = 0.3f * 20;   // N·m
constexpr float GM6020_MAX_TORQUE = 0.741f * 3;     // N·m

// [解析] 电机型号枚举。用它告诉 RM_Motor"我挂的是哪种电机"，
// [解析] 因为不同型号的 ID 规则、量纲换算全都不一样，类内部靠它来分支。
// [解析] enum class 是"强类型枚举"：写 RM_Motors::M3508 才能用，
// [解析] 不像普通 enum 那样能偷偷当成整数，能避免 + - * / 用错地方。
enum class RM_Motors
{
  M2006,    // 无减速箱
  // [解析] ↑ 注意这里的"无减速箱"是指"这个型号本身不带减速箱"，
  // [解析]   实际用的时候一般会自己配 P36 减速箱，这时构造函数要传 ratio = M2006_P36。
  M3508,    // 无减速箱
  // [解析] ↑ 同上，实际一般配 P19 减速箱，ratio = M3508_P19。
  GM6020,   // 电流控制
  // [解析] ↑ GM6020 的"电流控制模式"：cmd() 传的是力矩，单位 N·m。量程 ±16384。
  GM6020_V  // 电压控制
  // [解析] ↑ GM6020 的"电压控制模式"：cmd() 传的是电压，单位 V（0~24V 量程对应 ±25000）。
  // [解析]   这两种模式的 tx_id 也不同（0x1FE/0x2FE 和 0x1FF/0x2FF），见 rm_motor.cpp。
};

// [解析] RM_Motor：一个对象 = 总线上的一台大疆电机。
// [解析] 典型用法（完整例子见 applications/can_task.cpp）：
// [解析]   1) 定义对象：sp::RM_Motor m(1, sp::RM_Motors::GM6020_V);
// [解析]   2) 中断里收反馈：if (can1.rx_id == m.rx_id) m.read(can1.rx_data, stamp_ms);
// [解析]      读完后 m.angle / m.speed / m.torque / m.temperature 就是物理量了。
// [解析]   3) 任务里下指令：m.cmd(1.0f);  m.write(can1.tx_data);  can1.send(m.tx_id);
// [解析] ★ 线程安全提醒：read() 通常在 CAN 接收中断里调用，而 cmd()/读属性在主任务里，
// [解析]   这里没有加锁（也没用 volatile）。因为我们只读取"单个 float/uint8_t"这种
// [解析]   原子宽度的变量，且中断只写、任务只读，所以实践中不会出问题；
// [解析]   但如果你要读一个由多个变量组合出来的量，请自己在任务里做好一致性保护。
class RM_Motor
{
public:
  // motor_id: 电机ID, 取值: 1, 2, ..., 8
  // motor_type: 电机型号， 取值见`RM_Motors`
  // ratio: 减速比
  // [解析] 参数逐个说明：
  // [解析]   motor_id   —— 电机上拨码开关/上位机设的 ID，1~8。ID 决定收发的帧 ID。
  // [解析]   motor_type —— 型号，决定 ID 规则和量纲换算系数。
  // [解析]   ratio      —— 减速比（输出轴转 1 圈时转子转几圈）。
  // [解析]                    默认 1.0f 表示"直驱"（比如云台上的 GM6020）。
  // [解析]                    带减速箱的写法：M2006 传 M2006_P36，M3508 传 M3508_P19。
  // [解析]                    注意 ratio 不能为 0，否则下面所有除法都会得到 inf/nan。
  // [解析]   multi_circle —— true（默认）：angle 是"多圈累计角度"，可以一直累加、
  // [解析]                    断电重启后清零，用来做里程/丝杆行程很方便；
  // [解析]                    false：angle 只在 (-PI, PI] 之间跳，一过 180° 就翻号，
  // [解析]                    适合只关心"转了多少度"的云台。区别见 rm_motor.cpp 的 read()。
  // [解析] 副作用：构造函数会计算出 rx_id / tx_id 并清零所有状态量，不碰硬件、不发帧。
  RM_Motor(uint8_t motor_id, RM_Motors motor_type, float ratio = 1.0f, bool multi_circle = true);

  const uint16_t rx_id;  // 电机反馈帧ID
  // [解析] ↑ 电机发给我们的帧用的 ID。收到一帧后，拿 can1.rx_id 和它比一比，
  // [解析]   相等才说明"这帧是本电机的"，然后才交给 read() 解析。
  // [解析]   由 rm_motor.cpp 的 get_rx_id() 算出来（M2006/M3508 是 0x200+id，GM6020 是 0x204+id）。
  const uint16_t tx_id;  // 电机控制帧ID
  // [解析] ↑ 我们发指令时用的帧 ID，直接传给 can1.send(m.tx_id)。
  // [解析]   由 get_tx_id() 算出来。注意：1~4 号电机和 5~8 号电机是两组不同的 ID，
  // [解析]   因为一帧 8 字节最多装 4 台电机的量（每台 2 字节）。

  float angle;          // 只读! 单位: rad
  // [解析] ↑ 只读、由 read() 更新。rad 是弧度（一圈 = 2*PI ≈ 6.283）。
  // [解析]   已经除以减速比，是"输出轴"的角度。multi_circle = true 时是累计值（可能远大于 2*PI）。
  float speed;          // 只读! 单位: rad/s
  // [解析] ↑ 也只读、由 read() 更新，同样是输出轴侧的角速度。
  float torque;         // 只读! 单位: N·m
  // [解析] ↑ 由反馈里的"实际电流 raw"换算而来，是电机当前出力的估计值，不是我们下发的指令值。
  uint8_t temperature;  // 只读! 单位: 摄氏度
  // [解析] ↑ 电机内部温度。经验值：持续 80°C 以上该降功率，90°C 以上建议停机，
  // [解析]   否则电机内部会触发过温保护（表现为突然不出力）。

  // [解析] is_open()：这台电机"到目前为止有没有收到过反馈"。
  // [解析]   返回 true  = 至少成功 read() 过一次（电机上线过）。
  // [解析]   返回 false = 从开机到现在一帧都没收到（没上电 / 接线错 / ID 设错 / 波特率错）。
  // [解析]   注意它一旦变 true 就不会再变回 false，所以"是否掉线"要用下面的 is_alive()。
  bool is_open() const;
  // [解析] is_alive(now_ms)：判断电机"此刻是否还在线"。
  // [解析]   now_ms 传入当前系统毫秒数（在 FreeRTOS 里一般是 osKernelSysTick()）。
  // [解析]   返回 true = 收到过反馈，且距离最后一次反馈不到 100ms。
  // [解析]   为什么是 100ms：电机正常是每 1ms 回一帧，100ms 相当于允许丢 100 帧，
  // [解析]   既不会因为偶尔丢帧误报掉线，又能在真掉线后 0.1 秒内被发现，来得及做保护。
  bool is_alive(uint32_t now_ms) const;

  // [解析] read()：解析一帧电机反馈（8 字节），更新 angle/speed/torque/temperature。
  // [解析]   data     —— 指向收到的 8 字节原始数据（通常就是 can1.rx_data），
  // [解析]               调用者必须先用 rx_id 判断这帧确实属于本电机，否则读出来是乱的。
  // [解析]   stamp_ms —— 这次收到数据的时刻（毫秒），存下来给 is_alive() 用。
  // [解析]   副作用：会更新内部的多圈计数 circle_ / last_ecd_ / last_read_ms_。
  // [解析] ★ 这个函数是设计给"CAN 接收中断"里调用的，所以里面没有浮点以外的阻塞操作。
  void read(uint8_t * data, uint32_t stamp_ms);
  // [解析] write()：把之前 cmd() 存下来的指令，写进 8 字节发送缓冲区 data 里。
  // [解析]   data —— 指向 can1.tx_data（8 字节）。
  // [解析] ★ 关键：一帧最多装 4 台电机，每台占 2 字节，4 台各自调用一次 write() 拼进同一帧。
  // [解析]   所以顺序必须是：4 台都 cmd() + write() 之后，再 can1.send(tx_id) 一次发出去。
  // [解析]   const 表示它只读内部状态、改的是传进来的 data。
  void write(uint8_t * data) const;

  // 如果非`RM_Motors::GM6020_V`, 单位: N·m
  // 如果是`RM_Motors::GM6020_V`, 单位: V
  // [解析] cmd()：设置控制指令。这是"唯一"的指令入口，单位随型号变化，务必看清：
  // [解析]   M2006 / M3508 / GM6020（电流模式）—— 单位 N·m，是"输出轴侧"的期望力矩。
  // [解析]     内部会自动除以 ratio_ 换算到转子侧，再换算成 raw 值。正负号决定转向。
  // [解析]   GM6020_V（电压模式）—— 单位 V，范围约 ±24V（内部按 24V 对应 25000 换算）。
  // [解析]     前文 applications/can_task.cpp 里写 0.0f 就是"先不给电压"，安全调试起点。
  // [解析] 副作用：把换算并限幅后的 raw 值存进 cmd_raw_，等 write() 取用。
  // [解析] ★ 它只是"记住指令"，并不会立刻发出去，必须再调 write() + can1.send()。
  void cmd(float value);

private:
  // [解析] ↓ 下面 4 个是构造时就定死、之后不再变的量，所以加了 const。
  // [解析]   加 const 的好处：写代码时若不小心想改它们，编译器会直接报错。
  const uint8_t motor_id_;
  // [解析] ↑ 记住电机 ID，write() 要靠它算出"我该占这 8 字节里的哪 2 个字节"。
  const RM_Motors motor_type_;
  // [解析] ↑ 记住型号，每次换算都要用它查系数。
  const float ratio_;
  // [解析] ↑ 记住减速比，读的时候除、写的时候乘。
  const bool multi_circle_;
  // [解析] ↑ 记住是否需要多圈累计（false 时 angle 不累加 circle_）。

  // [解析] ↓ 下面 5 个是运行过程中会变的"状态"，都有明确初值，见 rm_motor.cpp 的构造函数。
  bool has_read_;
  // [解析] ↑ 是否已经成功读到过至少一帧。用来区分"电机没上线"和"电机真的在 0 位置"。
  uint32_t last_read_ms_;
  // [解析] ↑ 最后一次收到反馈的时刻（毫秒），is_alive() 用它做超时判断。
  // [解析]   注意：构造函数里没有初始化它，但 is_alive() 会先用 is_open() 短路保护，
  // [解析]   没读过时根本不会用到它，所以是安全的。
  int32_t circle_;
  // [解析] ↑ "已经转过的整圈数"，可以为负（反转）。int32_t 保证跑很久也不会溢出。
  uint16_t last_ecd_;
  // [解析] ↑ 上一次的编码器读数（0~8191），用来和这一次比较、判断有没有跨过 0 点。
  int16_t cmd_raw_;
  // [解析] ↑ cmd() 换算出来的最终指令值（就是真正要写进 CAN 帧的两个字节）。
  // [解析]   用有符号 16 位，正好对应协议里的 int16；写帧时拆成高字节 + 低字节。
};

}  // namespace sp

#endif  // SP__RM_MOTOR_HPP