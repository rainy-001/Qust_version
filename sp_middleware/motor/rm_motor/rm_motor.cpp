// [解析] ↓ 4 个"满量程 raw 值"（也就是控制量能到多大）。这些值不是随便定的，
// [解析]   raw 就是 CAN 帧里那两个字节的内容，是驱动板的认识范围。
constexpr int16_t M2006_MAX_RAW = 10000;
// [解析] ↑ M2006：官方手册给的电流控制量程是 ±10000。注意它不是 2 的幂，
// [解析]   所以网上很多照抄 M3508 代码（写 16384）的例程驱动 M2006 是有问题的。
constexpr int16_t M3508_MAX_RAW = 16384;
// [解析] ↑ M3508：量程 ±16384（= 2^14）。刚好是 13 位编码器 8192 的 2 倍，但两者没有因果关系，
// [解析]   只是官方就这么定的，背下来即可。
constexpr int16_t GM6020_MAX_RAW = 16384;
// [解析] ↑ GM6020 电流模式：同样是 ±16384。
constexpr int16_t GM6020_V_MAX_RAW = 25000;
// [解析] ↑ GM6020 电压模式：±25000 对应 ±24V。所以 1V ≈ 25000/24 ≈ 1041.7 个 raw。
// [解析]   注意这个值超过 int16 的一半（32767）但仍在 int16 范围内，所以能存下。

// [解析] ↓ 3 个"raw 电流 -> 输出轴力矩(N·m)"的换算系数。以 M2006 为例拆开看：
// [解析]   0.18f        —— 官方手册：M2006 输出轴额定力矩约 0.18 N·m（对应满电流）。
// [解析]   / M2006_P36  —— 换算到"转子侧"：减速箱把力矩放大了 36 倍，
// [解析]                   所以输出轴 0.18 对应转子侧 0.18/36。
// [解析]   * 10         —— 见 hpp 中 M2006_P36_MAX_TORQUE 的说明：这是原作者额外乘的放大系数，
// [解析]                   手册里没有直接给出这个 10 的来历，属于来历不明但收发双方口径一致。
// [解析]   / MAX_RAW    —— 把"满量程"归一化，这样乘上 raw 值就得到力矩。
// [解析] 结论：read() 算出的 torque 与 cmd() 下发的力矩用了【同一套系数】，
// [解析]   所以闭环控制时"读回来"和"发出去"能对上，可以放心用于对比和 PID；
// [解析]   但它的绝对值不要拿去和手册上的 N·m 逐条对账。
constexpr float M2006_RAW_TO_TORQUE = 0.18f / M2006_P36 * 10 / M2006_MAX_RAW;
constexpr float M3508_RAW_TO_TORQUE = 0.3f / M3508_P19 * 20 / M3508_MAX_RAW;
constexpr float GM6020_RAW_TO_TORQUE = 0.741f * 3 / GM6020_MAX_RAW;
// [解析] ↑ GM6020 这行没有 / 减速比，因为它是直驱云台电机，减速比就是 1。

// [解析] ↓ 上面系数的"倒数"，用来把"想要的力矩"反算成 raw 值。
// [解析]   为什么不直接写除法？因为除以一个常量，编译器也只能这么算，
// [解析]   写成常量乘法反而更清楚，而且编译期就能算好，运行时省一点时间。
// [解析] ★ 注意：这三个常量只是"数值上的倒数"，并没有额外语义，改动上面系数时它们不会自动跟着变，
// [解析]   所以改系数一定要两边同时改，否则 cmd() 和 read() 就对不上了。
constexpr float M2006_CMD_TO_RAW = 1.0f / M2006_RAW_TO_TORQUE;
constexpr float M3508_CMD_TO_RAW = 1.0f / M3508_RAW_TO_TORQUE;
constexpr float GM6020_CMD_TO_RAW = 1.0f / GM6020_RAW_TO_TORQUE;
constexpr float GM6020_V_CMD_TO_RAW = GM6020_V_MAX_RAW / 24.0f;
// [解析] ↑ 电压模式专用：25000 / 24V ≈ 1041.67 raw/V。
// [解析]   所以 cmd(12.0f) 会变成约 12500 个 raw，正好是半量程（12V 是一半的 24V）。

// [解析] get_rx_id()：计算"电机用哪个 ID 给我们发反馈"。
// [解析]   motor_id   —— 电机 ID，1~8。
// [解析]   motor_type —— 型号。
// [解析]   返回值     —— 要匹配的 CAN 帧 ID（标准帧，11 位）。
// [解析] 规律来自官方协议：
// [解析]   M2006 / M3508 —— 反馈 ID = 0x200 + 电机ID，即 0x201~0x208。
// [解析]   GM6020       —— 反馈 ID = 0x204 + 电机ID，即 0x205~0x20C。
// [解析]   注意 GM6020 的两个模式共用同一套反馈 ID，所以同一总线上
// [解析]   不能同时挂 ID 相同的电流版和电压版 6020，否则反馈会撞车。
uint16_t get_rx_id(uint8_t motor_id, RM_Motors motor_type)
{
  switch (motor_type) {
    case RM_Motors::M2006:
    case RM_Motors::M3508:
      return motor_id + 0x200;
    default:
      // [解析] default 覆盖 GM6020 和 GM6020_V 两种模式（它们的反馈 ID 规则一样）。
      return motor_id + 0x204;
  }
}

// [解析] get_tx_id()：计算"我们要用哪个 ID 发控制帧"。
// [解析]   motor_id   —— 电机 ID，1~8。
// [解析]   motor_type —— 型号（电流模式 GM6020 和电压模式 GM6020_V 的 ID 不同！）。
// [解析]   返回值     —— 发送帧 ID。
// [解析] ★ 为什么到处都在判断 "motor_id < 5"：
// [解析]   一帧 CAN 数据只有 8 字节，每台电机要占 2 字节，所以一帧最多带 4 台。
// [解析]   官方就把 8 个 ID 拆成两组：1~4 号用低 ID，5~8 号用高 ID（0x1FF/0x2FF 这组）。
uint16_t get_tx_id(uint8_t motor_id, RM_Motors motor_type)
{
  switch (motor_type) {
    case RM_Motors::GM6020:
      // [解析] 6020 电流模式：1~4 号用 0x1FE，5~8 号用 0x2FE。
      return motor_id < 5 ? 0x1FE : 0x2FE;
    case RM_Motors::GM6020_V:
      // [解析] 6020 电压模式：1~4 号用 0x1FF，5~8 号用 0x2FF。
      // [解析]   和电流模式只差最低位（0x1FE/0x1FF），抄代码时特别容易看漏，务必核对。
      return motor_id < 5 ? 0x1FF : 0x2FF;
    default:
      // [解析] M2006 / M3508：1~4 号用 0x200，5~8 号用 0x1FF。
      // [解析]   这两个 ID 和二进制的 0x201 之类容易混淆：
      // [解析]   0x200 是"控制帧"，0x201 是"1 号电机的反馈帧"，正好错开，所以能同时收发。
      return motor_id < 5 ? 0x200 : 0x1FF;
  }
}

// [解析] get_raw_to_torque()：按型号取出"raw 电流 -> N·m"的换算系数。
// [解析]   返回值就是前面那三个 XXX_RAW_TO_TORQUE 常量，单位 N·m / raw。
// [解析]   为什么要包成函数：read() 里是运行期才知道型号的，switch 比写一堆 if 清楚。
// [解析]   GM6020 和 GM6020_V 共用 default 分支，因为两者的反馈帧格式一样、都用电流算力矩。
float get_raw_to_torque(RM_Motors motor_type)
{
  switch (motor_type) {
    case RM_Motors::M2006:
      return M2006_RAW_TO_TORQUE;
    case RM_Motors::M3508:
      return M3508_RAW_TO_TORQUE;
    default:
      return GM6020_RAW_TO_TORQUE;
  }
}

// [解析] get_cmd_to_raw()：按型号取出"想给的量 -> raw"的换算系数，供 cmd() 使用。
// [解析]   注意这个函数和上面那个"不对称"：GM6020 的两种模式走的是不同分支，
// [解析]   因为电流模式按力矩换算（1/系数），电压模式按电压换算（1041.67 raw/V）。
float get_cmd_to_raw(RM_Motors motor_type)
{
  switch (motor_type) {
    case RM_Motors::M2006:
      return M2006_CMD_TO_RAW;
    case RM_Motors::M3508:
      return M3508_CMD_TO_RAW;
    case RM_Motors::GM6020:
      return GM6020_CMD_TO_RAW;
    default:
      return GM6020_V_CMD_TO_RAW;
  }
}

// [解析] get_max_raw()：按型号取出控制量的满量程，cmd() 用它做限幅。
// [解析]   作用很重要：如果算出来的 raw 超过量程就发出去，电机会收到一个"超范围"的值，
// [解析]   轻则按最大值输出（已经不是你要的了），重则触发保护甚至报错。
// [解析]   所以 cmd() 里一定会先夹到 [-max_raw, +max_raw]。
int16_t get_max_raw(RM_Motors motor_type)
{
  switch (motor_type) {
    case RM_Motors::M2006:
      return M2006_MAX_RAW;
    case RM_Motors::M3508:
      return M3508_MAX_RAW;
    case RM_Motors::GM6020:
      return GM6020_MAX_RAW;
    default:
      return GM6020_V_MAX_RAW;
  }
}

// [解析] 构造函数：下面这串 "冒号 + 一长串" 叫"初始化列表"，作用是在对象诞生时
// [解析] 把每个成员按顺序直接构造出来，比在函数体里一个个赋值效率略高，也是 C++ 的惯例写法。
// [解析] ★ 顺序坑：成员的真正初始化顺序由"它们在 hpp 里声明的顺序"决定，跟这里写的顺序无关。
// [解析]   这里写的顺序和声明顺序是一致的，所以不会踩坑；如果打乱了，
// [解析]   编译器会报警告，而且可能出现"用还没初始化的值去算另一个值"的诡异 bug。
