RM_Motor::RM_Motor(uint8_t motor_id, RM_Motors motor_type, float ratio, bool multi_circle)
: rx_id(get_rx_id(motor_id, motor_type)),
  tx_id(get_tx_id(motor_id, motor_type)),
  angle(0),
  speed(0),
  torque(0),
  temperature(0),
  motor_id_(motor_id),
  motor_type_(motor_type),
  ratio_(ratio),
  multi_circle_(multi_circle),
  has_read_(false),
  circle_(0),
  cmd_raw_(0)
  // [解析] ↑ circle_ 从 0 开始数圈，cmd_raw_ 从 0 开始（= 不给力），都是安全初值。
  // [解析] ★ 注意这里没有初始化 last_ecd_（编码器上次读数）和 last_read_ms_（时间戳）：
  // [解析]   last_ecd_ 靠 read() 里 "if (!has_read_)" 那段在第一帧时补齐；
  // [解析]   last_read_ms_ 靠 is_alive() 里的 is_open() 短路保护。属于"故意不初始化"，不是漏写。
{
  // [解析] 函数体是空的：构造函数只做"记账"，不碰硬件、不发 CAN 帧。
  // [解析]   真正的收发发生在 can_task.cpp 里第一次 cmd() / write() / read() 的时候。
}

// [解析] is_open()：直接把内部标志 has_read_ 返回出去。
// [解析]   写成一行函数而不是让外面直接访问 has_read_，是为了"只暴露需要的信息"，
// [解析]   外面就无法误改这个标志了。
bool RM_Motor::is_open() const { return has_read_; }

// [解析] is_alive()：判断电机此刻是否在线。
// [解析]   is_open()             —— 先确保"历史上收到过反馈"，没收到过就直接 false。
// [解析]                            这个"先判断"同时起了保护作用：没有它，第一次调用时
// [解析]                            last_read_ms_ 还是未初始化的垃圾值，减法结果毫无意义。
// [解析]   now_ms - last_read_ms_ < 100 —— 距离最后一次反馈不到 100ms 才算在线。
// [解析]   两个细节值得注意：
// [解析]     1) 用"减法"而不是比较大小，是为了让定时器溢出（回绕）时结果依然正确，
// [解析]        这是嵌入式里判断时间间隔的标准写法，务必养成习惯；
// [解析]     2) 100 这个阈值是经验值：电机正常每 1ms 回一帧，允许连续丢 100 帧，
// [解析]        对绝大多数控制周期（1~5ms）来说，被误判掉线的概率极低，反应速度也够快。
bool RM_Motor::is_alive(uint32_t now_ms) const
{
  return is_open() && (now_ms - last_read_ms_ < 100);
}

// [解析] read()：本文件最重要、也最需要看懂的函数。它把 8 字节反馈解析成物理量。
// [解析] 这 8 字节的排列是官方协议规定的（大端序，高字节在前）：
// [解析]   data[0..1] 编码器机械角度（uint16，0~8191）
// [解析]   data[2..3] 转子转速（int16，单位 rpm）
// [解析]   data[4..5] 实际电流 raw（int16，可正可负）
// [解析]   data[6]    温度（摄氏度）
// [解析]   data[7]    保留/其它
// [解析] ★ 这段代码运行在 CAN 接收中断里，所以每一行都要尽量快，不要在这里加打印。
void RM_Motor::read(uint8_t * data, uint32_t stamp_ms)
{
  // 更新时间戳
  last_read_ms_ = stamp_ms;
  // [解析] 存下"这一帧是什么时候到的"，is_alive() 靠它判断在线。

  // 数据解析
  // [解析] 下面三行是典型的"字节拼接"，也是新手最容易看懵的位运算。以第一行为例：
  // [解析]   data[0] << 8  —— 把低地址那个字节当作"高 8 位"，左移 8 位挪到上面去；
  // [解析]   | data[1]     —— 再用按位或把第二个字节接到低 8 位。
  // [解析]   合起来就是"大端序(big-endian)读取一个 16 位数"。
  // [解析] ★ 为什么要这样拼：CAN 帧是按字节传的，而电机协议规定了"高字节先发"，
  // [解析]   所以 data[0] 是高位。如果反过来拼，读出来的值会莫名其妙地很怪（字节序反了）。
  // [解析] ★ 还要注意类型：data[] 是 uint8_t，参与运算前会被提升成 int，
  // [解析]   左移 8 位不会溢出；只有赋给 int16_t 的那两行才发生"截断成有符号 16 位"。
  uint16_t angle_ecd = (data[0] << 8) | data[1];
  // [解析] ↑ 编码器机械角度。范围 0~8191，注意它是"无符号"的，而且 0 点由电机的机械零点决定，
  // [解析]   跟"车头朝哪"没关系，装车后需要自己校准一次零位（见 joint_controller 的 init 逻辑）。
  int16_t speed_rpm = (data[2] << 8) | data[3];
  // [解析] ↑ 转速，单位 rpm（转/分）。用 int16_t 因为要能表示反转（负值）。
  // [解析]   大疆电机的额定转速约 ±8500 rpm，int16 的 ±32767 足够表示。
  int16_t current_raw = (data[4] << 8) | data[5];
  // [解析] ↑ 实际电流对应的 raw 值（力矩的"原始形态"），范围约 ±16384（M2006 约 ±10000）。
  // [解析]   之所以反馈里也是 raw 而不是直接给安培数，是因为手册按 raw 标定量程。

  // 首次读取时, 初始化last_ecd_
  // [解析] 第一帧的特殊处理：此时 last_ecd_ 还没有意义，如果直接拿它做减法求圈数，
  // [解析]   会算出一个乱七八糟的圈数。所以第一帧只做"记住起点"，不算圈也不报错。
  // [解析]   这也解释了为什么 has_read_ 要存在：它是"多圈计数是否可信"的判据。
  if (!has_read_) {
    has_read_ = true;
    last_ecd_ = angle_ecd;
  }

  // 多圈编码
  // [解析] 编码器一圈只有 0~8191，转过一圈就会从 8191 掉回 0。
  // [解析]   如果只看编码器值，你永远不知道电机转了几圈，所以要用 circle_ 自己数。
  // [解析] ★ 判据为什么是 4096：4096 正好是半圈（8192/2）。
  // [解析]   假设两次读取之间电机不可能真的转过半圈以上（控制周期只有 1ms，做不到），
  // [解析]   那么"差值突然很大"就只可能是"编码器跨过了 0 点"：
  // [解析]     差值为大正数（如 8191 -> 0 时算出的是 -8191）说明刚才是往回绕，圈数要减 1；
  // [解析]     大负数说明往前绕，圈数加 1；取了半个量程做阈值，是为了抗噪声。
  // [解析]   这里用 4096 而角度零点用了 4095，两个数很接近但不是同一个东西，别搞混。
  // [解析] ★ 局限：如果电机转得极快、或中断被长时间阻塞导致两帧间隔很大，
  // [解析]   一旦真的转过半圈，圈数就会被数错一（表现为角度突然跳 2*PI）。属于原理上的取舍。
  if (angle_ecd - last_ecd_ > 4096)
    circle_--;
  else if (angle_ecd - last_ecd_ < -4096)
    circle_++;
  last_ecd_ = angle_ecd;
  // [解析] ↑ 把本次读数存下来，给下一次比较用。这一行在 if/else 之外，所以无论有没有翻圈都会执行。

  // [解析] ↓ 这一步把"编码器计数"变成"弧度"，是三段运算：
  // [解析]   angle_ecd - 4095 —— 减掉机械零点（约半圈的 4096），把 0~8191 平移到约 -4095~+4096，
  // [解析]                        这样一个完整的正负范围就有了，弧度才会正负对称。
  // [解析]      ★ 注意：这里减的是 4095 而不是 4096，所以零位有 1 个计数的偏移
  // [解析]        （约 0.00077 弧度，肉眼完全看不出），大疆官方例程也多处用 4095，属于历史写法。
  // [解析]   / 8192 * 2 * SP_PI —— 换算成弧度：先归一化成"圈数"(0~1)，再乘一圈的弧度 2*PI。
  // [解析]                        结果范围约 -PI ~ +PI，即"单圈内的绝对角度"。
  // [解析]   / ratio_       —— 从"转子角度"换算成"输出轴角度"（减速箱后的角度）。
  float angle_rad = float(angle_ecd - 4095) / 8192 * 2 * SP_PI / ratio_;

  // 更新公有属性
  // [解析] ↓ 三目运算符 (条件 ? A : B)：multi_circle_ 为 true 时输出"单圈角度 + 圈数*2*PI"，
  // [解析]   也就是累计角度（可以超过 ±PI，可以一直增大）；为 false 时只给单圈角度。
  // [解析]   circle_ * 2 * SP_PI / ratio_ —— 一圈是 2*PI 弧度，同样要除以减速比换成输出轴口径，
  // [解析]   注意"先乘圈数再除减速比"和"先除再乘"在数学上等价，但顺序不同会有微小浮点误差，
  // [解析]   这里两种写法混用了（angle_rad 已经除过，圈数部分才除），看起来会有点绕。
  this->angle = multi_circle_ ? angle_rad + circle_ * 2 * SP_PI / ratio_ : angle_rad;
  // [解析] ↑ speed 换算：(rpm) -> (rps) -> (rad/s) -> 输出轴。
  // [解析]   / 60 是把"每分"变成"每秒"，* 2 * SP_PI 是"圈"变"弧度"，/ ratio_ 是转子变输出轴。
  this->speed = float(speed_rpm) / 60 * 2 * SP_PI / ratio_;
  // [解析] ★ 对比一下 speed 和 torque 里 ratio_ 的位置：speed 是"除以" ratio_，
  // [解析]   而 torque 这里是"乘以" ratio_。表面上方向相反，但下面会看到
  // [解析]   torque 的系数里已经除过一次，所以最终减速比是被约掉的，不是净放大。
  this->torque = float(current_raw) * get_raw_to_torque(motor_type_) * ratio_;
  // [解析] ↑ torque 换算：raw * (N·m/raw) * ratio_。
  // [解析] 注意：get_raw_to_torque() 返回的系数里已经"除以"过减速比，
  // [解析]   这里又"乘以"一次 ratio_，两次减速比正好抵消。
  // [解析]   也就是说：对 M2006/M3508 而言，减速比对这个 torque 的数值没有影响，
  // [解析]   真正决定大小的是手册标称力矩、放大系数和满量程 raw。
  // [解析]   使用建议：把它当作"和下发指令同口径的力矩估计量"，用于 PID 反馈和过载判断，
  // [解析]   不要拿去和手册上的 N·m 数值逐条对账。
  this->temperature = data[6];
  // [解析] ↑ 温度是单字节，直接就是摄氏度，不需要任何换算。
  // [解析]   data[7] 在本函数里没有使用（协议里一般是保留位或错误码）。
}

// [解析] write()：把 cmd_raw_ 这两个字节，写进 8 字节发送缓冲区的"属于我的位置"。
// [解析] ★ 核心理解：这一帧是"4 台电机共用"的。协议规定 8 个字节按顺序放 4 台电机，每台 2 字节：
// [解析]     字节 0~1 -> 本组第 1 台电机（高字节在前，大端序，和 read() 里的拼法对称）
// [解析]     字节 2~3 -> 本组第 2 台电机
// [解析]     字节 4~5 -> 本组第 3 台电机
// [解析]     字节 6~7 -> 本组第 4 台电机
// [解析]   所以每台电机只管写自己那 2 个字节，谁都不许动别人的——这就是调用者必须
// [解析]   "先让 4 台都 write()，再统一 send() 一次"的原因。
// [解析] ★ 下标公式 (motor_id_ - 1) % 4 * 2 拆开看：
// [解析]   motor_id_ - 1 —— ID 从 1 开始，先减 1 变成从 0 开始的序号；
// [解析]   % 4          —— 取模，让 5~8 号电机映射回 0~3（因为第 5 台又回到第 1 个位置）；
// [解析]   * 2          —— 每个电机占 2 个字节，所以序号要乘 2 换成字节偏移。
// [解析]   例：motor_id_=1 -> 偏移 0；=4 -> 偏移 6；=5 -> 偏移 0（新的一帧，1~4 号在另一组 ID 上）。
void RM_Motor::write(uint8_t * data) const
{
  // [解析] ↓ 取 int16 的高 8 位（大端：高字节先放低地址）。
  // [解析]   >> 8 对"负数"来说是算术右移，高位补的是符号位 1，所以 -1 >> 8 得到 0xFF，
  // [解析]   赋给 uint8_t 时自动截断成 0xFF。配合下面低字节的 0xFF，接收方拼回来仍是 -1，
  // [解析]   结果正确，所以这里不需要额外处理负数。
  data[(motor_id_ - 1) % 4 * 2 + 0] = cmd_raw_ >> 8;
  // [解析] ↓ 取低 8 位。cmd_raw_ 是 int16_t，赋给 uint8_t 时隐式截断，只保留低 8 位。
  data[(motor_id_ - 1) % 4 * 2 + 1] = cmd_raw_;
}

// [解析] cmd()：设置控制指令，是唯一的下发入口。内部做"换算 + 限幅 + 暂存"三件事。
// [解析]   value —— 期望的控制量。单位随型号变：
// [解析]      M2006 / M3508 / GM6020   -> N·m（输出轴力矩，正负决定转向）
// [解析]      GM6020_V                -> V（约 ±24V）
// [解析] 副作用：只更新成员 cmd_raw_，不发 CAN 帧！必须配合 write() + can.send()。
// [解析] ★ 为什么要 / ratio_：value 是"输出轴想要的力矩"，
// [解析]   而驱动板控制的是转子，减速箱把力矩放大了 ratio 倍，
// [解析]   所以要除以 ratio_ 才能得到"转子侧该出多少力"。
void RM_Motor::cmd(float value)
{
  // [解析] auto 让编译器自己推断类型，这里 raw 是 float。两步合在一起：
  // [解析]   value / ratio_            —— 输出轴口径 -> 转子口径
  // [解析]   * get_cmd_to_raw(...)     —— 物理量 -> raw（电流模式是"力矩*倒数系数"，电压模式是"V*1041.67"）
  auto raw = value / ratio_ * get_cmd_to_raw(motor_type_);
  auto max_raw = get_max_raw(motor_type_);

  // [解析] ↓ 经典限幅（clamp）：把 raw 夹到 [-max_raw, +max_raw]。
  // [解析]   注意这里故意用两个独立 if，而不是 else if——因为两个条件互斥，
  // [解析]   用两个 if 读起来更直观：先夹上限，再夹下限。
  // [解析]   raw 是 float，max_raw 是 int16_t，比较时 int16_t 会自动转成 float，没问题。
  if (raw > max_raw) raw = max_raw;
  if (raw < -max_raw) raw = -max_raw;

  // 更新私有属性cmd_raw_, 待write()使用
  // [解析] ↓ 存进 int16_t 成员。注意 raw 是 float，赋值时会发生"浮点截断成整数"：
  // [解析]   小数部分直接丢掉（不是四舍五入），误差最多 1 个 raw，完全可忽略。
  // [解析]   截断后的值一定是安全的：因为上面已经夹进 ±max_raw，而 max_raw 最大 25000 < 32767，
  // [解析]   所以不会溢出 int16_t。
  cmd_raw_ = raw;
}

